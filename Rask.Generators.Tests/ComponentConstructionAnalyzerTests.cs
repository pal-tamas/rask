using System.Collections.Immutable;
using System.Reflection;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Diagnostics;
using Rask.Generators.Analyzers;

namespace Rask.Generators.Tests;

public class ComponentConstructionAnalyzerTests
{
    [Fact]
    public async Task NewBuiltInTag_ReportsRask014()
    {
        var src = """
                  using Rask.Core.Components;
                  class C
                  {
                      void M() { var x = new Div(null); }
                  }
                  """;

        var diagnostics = await GetDiagnosticsAsync(src);

        var d = Assert.Single(diagnostics);
        Assert.Equal("RASK014", d.Id);
        Assert.Contains("Div", d.GetMessage());
    }

    [Fact]
    public async Task NewUserComponent_ReportsRask014()
    {
        var src = """
                  using Rask.Core;
                  namespace Demo;
                  public sealed class Counter : Component
                  {
                      public override Component Render() => this;
                  }
                  class Caller { void M() { var x = new Counter(); } }
                  """;

        var diagnostics = await GetDiagnosticsAsync(src);

        var d = Assert.Single(diagnostics);
        Assert.Equal("RASK014", d.Id);
    }

    [Fact]
    public async Task TargetTypedNewComponent_ReportsRask014()
    {
        var src = """
                  using Rask.Core.Components;
                  class C
                  {
                      Div M() { Div d = new(null); return d; }
                  }
                  """;

        var diagnostics = await GetDiagnosticsAsync(src);

        var d = Assert.Single(diagnostics);
        Assert.Equal("RASK014", d.Id);
    }

    [Fact]
    public async Task NewPropsRecord_NoDiagnostic()
    {
