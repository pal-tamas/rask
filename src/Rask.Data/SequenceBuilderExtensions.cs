using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;

namespace Rask.Data;

/// <summary>
///     <c>b.Property(p =&gt; p.Id).FromSequence("Providers", start: 1000)</c> — a key the database hands out before the row
///     is inserted, so the aggregate knows it while it is still being built.
/// </summary>
public static class SequenceBuilderExtensions
{
    /// <summary>The annotation naming the sequence, until the model is finalized for its provider.</summary>
    internal const string Annotation = "Rask:Sequence";

    /// <summary>The annotation holding the sequence's first value.</summary>
    internal const string StartAnnotation = "Rask:SequenceStart";

    /// <summary>
    ///     Takes the key of each new row from a database sequence, the moment the row is added — before its insert.
    /// </summary>
    /// <param name="property">The key's builder: an <see cref="int" />, a <see cref="long" />, or a strongly-typed id over one.</param>
    /// <param name="name">The sequence's name; the entity's name and <c>Ids</c> when left out — <c>ProviderIds</c>.</param>
    /// <param name="start">The first value it hands out.</param>
    /// <returns>The same builder.</returns>
    /// <remarks>
    ///     <para>
    ///         A sequence on SQL Server and on PostgreSQL, made by the migration from the model. SQLite has none, so there
    ///         it is a row of Rask's own <c>__RaskSequences</c> table, advanced in one statement under SQLite's writer
    ///         lock — and started above the table's highest key, so an existing table is never handed a key it holds.
    ///     </para>
    ///     <para>
    ///         Unlike an identity column, the value is there before the save: an aggregate that derives something from its
    ///         own key — a tenant's <c>p&lt;id&gt;</c> — saves once, and a key the app assigned and retried on a collision is
    ///         no longer needed.
    ///     </para>
    /// </remarks>
    /// <exception cref="InvalidOperationException">The key is not stored as an integer.</exception>
    public static PropertyBuilder FromSequence(this PropertyBuilder property, string? name = null, long start = 1)
    {
        ArgumentNullException.ThrowIfNull(property);

        var metadata = property.Metadata;
        var stored = metadata.GetValueConverter()?.ProviderClrType ?? metadata.ClrType;
        if (stored != typeof(int) && stored != typeof(long))
        {
            throw new InvalidOperationException(
                $"FromSequence hands out whole numbers, and '{metadata.DeclaringType.ClrType.Name}.{metadata.Name}' is " +
                $"stored as {stored.Name}. Call it on an int or long key, or a strongly-typed id over one.");
        }

        if (name is not null)
        {
            ArgumentException.ThrowIfNullOrWhiteSpace(name);
        }

        var sequence = name ?? metadata.DeclaringType.ClrType.Name + "Ids";

        // Never generated by the store: no identity column, the key is set as the row is added.
        property.ValueGeneratedNever();
        property.HasValueGenerator((key, _) => new SequenceValueGenerator(sequence, start, key));
        metadata.SetAnnotation(Annotation, sequence);
        metadata.SetAnnotation(StartAnnotation, start);
        return property;
    }

    /// <inheritdoc cref="FromSequence(PropertyBuilder, string?, long)" />
    /// <typeparam name="TKey">The key's type.</typeparam>
    public static PropertyBuilder<TKey> FromSequence<TKey>(this PropertyBuilder<TKey> property, string? name = null, long start = 1)
    {
        FromSequence((PropertyBuilder)property, name, start);
        return property;
    }
}
