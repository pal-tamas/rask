using System.Diagnostics.CodeAnalysis;

namespace Rask.Data;

/// <summary>
///     Writes each save of an <see cref="Audited" /> aggregate as a row of the app's own audit table, in place of Rask's
///     <see cref="AuditEntry" />: for a table whose old rows were written another way, and must go on being written so.
/// </summary>
/// <typeparam name="TRow">The app's audit row: an entity its model maps.</typeparam>
/// <typeparam name="TUserId">What the app's users are keyed by: a <see cref="Guid" />, an <see cref="int" /> or a <see cref="long" />.</typeparam>
/// <remarks>
///     <para>
///         Named once in the app's <c>IRaskModel</c>, which maps <typeparamref name="TRow" /> and leaves
///         <see cref="AuditEntry" /> out: <c>public static void Model(ModelBuilder m) =&gt; m.AuditAs(new LegacyAudits());</c>
///     </para>
///     <para>
///         <see cref="Row" /> is handed everything the save did (<see cref="AuditedWrite{TUserId}" />) and decides what the
///         row says: the whole aggregate as JSON or <see cref="AuditFormat.Values" />' text, only what changed, a system
///         user's id or null for nobody. The row is added to the same save; when the aggregate's key is generated by the
///         database, <see cref="Row" /> is asked once more after the rows went out, and the columns whose value moved are
///         written again before the save commits.
///     </para>
/// </remarks>
public abstract class AuditFormat<[DynamicallyAccessedMembers(DataTrimming.Entity)] TRow, TUserId> : AuditFormat
    where TRow : class
    where TUserId : struct
{
    /// <summary>Creates the format.</summary>
    /// <exception cref="NotSupportedException"><typeparamref name="TUserId" /> is no <see cref="Guid" />, <see cref="int" /> or <see cref="long" />.</exception>
    protected AuditFormat() => AuditUser.Demand<TUserId>();

    /// <summary>The row that records <paramref name="write" />.</summary>
    /// <param name="write">One save of one audited aggregate.</param>
    /// <returns>A new row; Rask adds it to the save.</returns>
    public abstract TRow Row(AuditedWrite<TUserId> write);

    /// <inheritdoc />
    internal sealed override Type RowType => typeof(TRow);

    /// <inheritdoc />
    internal sealed override bool ReadsSnapshot => true;

    /// <inheritdoc />
    internal sealed override object? User() => AuditUser.Of<TUserId>();

    /// <inheritdoc />
    internal sealed override object RowOf(Type aggregate, AuditDraft draft, object? user, DateTime at) =>
        Row(new AuditedWrite<TUserId>(aggregate, draft.Action, draft.Key, draft.Was, draft.Is, draft.Changed, (TUserId?)user, at));
}
