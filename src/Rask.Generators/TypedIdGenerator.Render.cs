using System.Text;
using Rask.Generators.Shared;

namespace Rask.Generators;

public sealed partial class TypedIdGenerator
{
    private const string Culture = "global::System.Globalization.CultureInfo.InvariantCulture";
    private const string Integer = "global::System.Globalization.NumberStyles.Integer";
    private const string NotNullWhenTrue = "[global::System.Diagnostics.CodeAnalysis.NotNullWhen(true)] ";

    private static string Render(TypedId id)
    {
        var name = id.Name;
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();

        if (id.Namespace is not null)
        {
            sb.Append("namespace ").Append(id.Namespace).AppendLine(";");
            sb.AppendLine();
        }

        if (!id.HasJsonConverter)
        {
            sb.Append("[global::System.Text.Json.Serialization.JsonConverter(typeof(").Append(name)
                .AppendLine(".__JsonConverter))]");
        }

        sb.Append("readonly partial record struct ").Append(name)
            .Append(" : global::System.ISpanParsable<").Append(name).AppendLine(">");
        sb.AppendLine("{");

        AppendFactories(sb, id);
        AppendInterfaceMembers(sb, id);

        if (!id.HasToString)
        {
            sb.AppendLine("    /// <summary>The value alone — what a URL, a log line and <see cref=\"Parse\" /> read.</summary>");
            sb.Append("    public override string ToString() => ").Append(ToStringText(id.Value)).AppendLine(";");
            sb.AppendLine();
        }

        if (!id.HasJsonConverter)
        {
            AppendJsonConverter(sb, id);
        }

        sb.AppendLine("}");
        return sb.ToString();
    }

    // New (a Guid's only), Parse and TryParse: the members an author calls by name.
    private static void AppendFactories(StringBuilder sb, TypedId id)
    {
        var name = id.Name;
        if (id.Value == TypedIdValue.Guid && !id.HasNew)
        {
            sb.AppendLine("    /// <summary>A new id: a version-7 <see cref=\"global::System.Guid\" />, time-ordered, so the key's index stays append-only.</summary>");
            sb.Append("    public static ").Append(name).AppendLine(" New() => new(global::System.Guid.CreateVersion7());");
            sb.AppendLine();
        }

        if (!id.HasParse)
        {
            sb.Append("    /// <summary>The id <paramref name=\"s\" /> spells, as <see cref=\"ToString\" /> writes it.</summary>");
            sb.AppendLine();
            sb.Append("    public static ").Append(name).Append(" Parse(string s) => new(").Append(ParseText(id.Value)).AppendLine(");");
            sb.AppendLine();
        }

        if (!id.HasTryParse)
        {
            sb.AppendLine("    /// <summary>The id <paramref name=\"s\" /> spells, or false when it spells none.</summary>");
            sb.Append("    public static bool TryParse(").Append(NotNullWhenTrue).Append("string? s, out ").Append(name)
                .AppendLine(" result)");
            sb.AppendLine("    {");
            AppendTryParseBody(sb, id.Value, "s");
            sb.AppendLine("    }");
            sb.AppendLine();
        }

    }

    private static void AppendInterfaceMembers(StringBuilder sb, TypedId id)
    {
        var name = id.Name;
        var parsable = "global::System.IParsable<" + name + ">";
        var spanParsable = "global::System.ISpanParsable<" + name + ">";

        sb.Append("    static ").Append(name).Append(' ').Append(parsable)
            .AppendLine(".Parse(string s, global::System.IFormatProvider? provider) => Parse(s);");
        sb.AppendLine();
        sb.Append("    static bool ").Append(parsable).Append(".TryParse(").Append(NotNullWhenTrue)
            .Append("string? s, global::System.IFormatProvider? provider, out ").Append(name)
            .AppendLine(" result) => TryParse(s, out result);");
        sb.AppendLine();
        sb.Append("    static ").Append(name).Append(' ').Append(spanParsable)
            .Append(".Parse(global::System.ReadOnlySpan<char> s, global::System.IFormatProvider? provider) => new(")
            .Append(SpanParseText(id.Value)).AppendLine(");");
        sb.AppendLine();
        sb.Append("    static bool ").Append(spanParsable)
            .Append(".TryParse(global::System.ReadOnlySpan<char> s, global::System.IFormatProvider? provider, out ")
            .Append(name).AppendLine(" result)");
        sb.AppendLine("    {");
        AppendTryParseBody(sb, id.Value, "s", span: true);
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static string ParseText(TypedIdValue value) => value switch
    {
        TypedIdValue.Int32 => "int.Parse(s, " + Integer + ", " + Culture + ")",
        TypedIdValue.Int64 => "long.Parse(s, " + Integer + ", " + Culture + ")",
        TypedIdValue.Guid => "global::System.Guid.Parse(s)",
        _ => "s ?? throw new global::System.ArgumentNullException(nameof(s))",
    };

    private static string SpanParseText(TypedIdValue value) => value switch
    {
        TypedIdValue.Int32 => "int.Parse(s, " + Integer + ", " + Culture + ")",
        TypedIdValue.Int64 => "long.Parse(s, " + Integer + ", " + Culture + ")",
        TypedIdValue.Guid => "global::System.Guid.Parse(s)",
        _ => "s.ToString()",
    };

    private static void AppendTryParseBody(StringBuilder sb, TypedIdValue value, string s, bool span = false)
    {
        switch (value)
        {
            case TypedIdValue.Int32:
            case TypedIdValue.Int64:
                var keyword = value == TypedIdValue.Int32 ? "int" : "long";
                sb.Append("        var parsed = ").Append(keyword).Append(".TryParse(").Append(s).Append(", ")
                    .Append(Integer).Append(", ").Append(Culture).AppendLine(", out var number);");
                sb.AppendLine("        result = new(number);");
                sb.AppendLine("        return parsed;");
                break;
            case TypedIdValue.Guid:
                sb.Append("        var parsed = global::System.Guid.TryParse(").Append(s).AppendLine(", out var guid);");
                sb.AppendLine("        result = new(guid);");
                sb.AppendLine("        return parsed;");
                break;
            default:
                if (span)
                {
                    sb.Append("        result = new(").Append(s).AppendLine(".ToString());");
                    sb.AppendLine("        return true;");
                    break;
                }

                sb.Append("        result = ").Append(s).Append(" is null ? default : new(").Append(s).AppendLine(");");
                sb.Append("        return ").Append(s).AppendLine(" is not null;");
                break;
        }
    }

    private static string ToStringText(TypedIdValue value) => value switch
    {
        TypedIdValue.Int32 or TypedIdValue.Int64 => "Value.ToString(" + Culture + ")",
        TypedIdValue.Guid => "Value.ToString()",
        _ => "Value ?? \"\"",
    };

    private static void AppendJsonConverter(StringBuilder sb, TypedId id)
    {
        var name = id.Name;
        const string Reader = "ref global::System.Text.Json.Utf8JsonReader reader, global::System.Type typeToConvert, global::System.Text.Json.JsonSerializerOptions options";
        const string Writer = "global::System.Text.Json.Utf8JsonWriter writer, ";

        sb.AppendLine("    // The id is its value on the wire — 42, not { \"Value\": 42 } — and a dictionary key spelled as Parse reads it.");
        sb.AppendLine("    [global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]");
        sb.Append("    internal sealed class __JsonConverter : global::System.Text.Json.Serialization.JsonConverter<").Append(name).AppendLine(">");
        sb.AppendLine("    {");
        sb.Append("        public override ").Append(name).Append(" Read(").Append(Reader).AppendLine(") =>");
        sb.Append("            ").Append(ReadText(id.Value)).AppendLine(";");
        sb.AppendLine();
        sb.Append("        public override void Write(").Append(Writer).Append(name)
            .AppendLine(" value, global::System.Text.Json.JsonSerializerOptions options) =>");
        sb.Append("            ").Append(WriteText(id.Value)).AppendLine(";");
        sb.AppendLine();
        sb.Append("        public override ").Append(name).Append(" ReadAsPropertyName(").Append(Reader).AppendLine(") =>");
        sb.AppendLine("            Parse(reader.GetString()!);");
        sb.AppendLine();
        sb.Append("        public override void WriteAsPropertyName(").Append(Writer).Append(name)
            .AppendLine(" value, global::System.Text.Json.JsonSerializerOptions options) =>");
        sb.AppendLine("            writer.WritePropertyName(value.ToString());");
        sb.AppendLine("    }");
    }

    // A number arrives as a number; one written as text by a client that quotes numbers is read too.
    private static string ReadText(TypedIdValue value) => value switch
    {
        TypedIdValue.Int32 => "reader.TokenType == global::System.Text.Json.JsonTokenType.String ? Parse(reader.GetString()!) : new(reader.GetInt32())",
        TypedIdValue.Int64 => "reader.TokenType == global::System.Text.Json.JsonTokenType.String ? Parse(reader.GetString()!) : new(reader.GetInt64())",
        TypedIdValue.Guid => "new(reader.GetGuid())",
        _ => "new(reader.GetString()!)",
    };

    private static string WriteText(TypedIdValue value) => value switch
    {
        TypedIdValue.Int32 or TypedIdValue.Int64 => "writer.WriteNumberValue(value.Value)",
        _ => "writer.WriteStringValue(value.Value)",
    };
}
