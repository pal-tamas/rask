using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace Rask.Generators;

public sealed partial class ValueObjectFactoryGenerator
{
    // The value objects of one value a form's model may hold as they are (`public TankCapacity? Size { get; set; }`),
    // registered as the assembly starts: what a control bound to one shows, how it is made from what is typed, and its
    // field. One class per assembly, named after it, so two assemblies that see each other's internals do not clash.
    private static void EmitFields(SourceProductionContext context, ImmutableArray<ValueObject> all, string assembly)
    {
        var held = all.Distinct().Where(static v => v.HeldByForms)
            .OrderBy(static v => v.FullyQualifiedName, System.StringComparer.Ordinal).ToList();
        var grouped = all.Distinct().Where(static v => v.GroupedByForms)
            .OrderBy(static v => v.FullyQualifiedName, System.StringComparer.Ordinal).ToList();
        if (held.Count == 0 && grouped.Count == 0)
        {
            return;
        }

        var s = new StringBuilder();
        s.AppendLine("// <auto-generated/>");
        s.AppendLine("#nullable enable");
        s.AppendLine();
        s.Append("internal static class __RaskValueFields_").Append(Identifier(assembly)).AppendLine();
        s.AppendLine("{");
        s.AppendLine("    [global::System.Runtime.CompilerServices.ModuleInitializer]");
        s.AppendLine("    internal static void Register()");
        s.AppendLine("    {");
        foreach (var value in held)
        {
            var member = value.Parameters[0];
            s.Append("        ").Append(Rules).Append(".Field<").Append(value.FullyQualifiedName).Append(", ").Append(member.Type)
                .Append(">(static v => v.").Append(member.Name).Append(", ").Append(value.FullyQualifiedName).Append(".TryCreate, ")
                .Append(HasField(value) ? "static () => " + value.FullyQualifiedName + ".__Field" : "null").AppendLine(");");
        }

        foreach (var value in grouped)
        {
            var draft = value.FullyQualifiedName + ".__Draft";
            s.Append("        ").Append(Rules).Append(".Group<").Append(value.FullyQualifiedName).Append(", ").Append(draft)
                .Append(">(static () => new ").Append(draft).Append("(), ")
                .Append(HasField(value) ? "static () => " + value.FullyQualifiedName + ".__Field" : "null").AppendLine(");");
        }

        s.AppendLine("    }");
        s.AppendLine("}");
        context.AddSource("RaskValueFields.g.cs", SourceText.From(s.ToString(), Encoding.UTF8));
    }

    // What AppendField writes a `__Field` for.
    private static bool HasField(ValueObject value) =>
        value.HasFieldSeam && value.ValueBase is "Text" or "Number" or "Integer" or "Day" or "Moment" or "Range";

    private static string Identifier(string assembly) =>
        new([.. assembly.Select(static c => char.IsLetterOrDigit(c) ? c : '_')]);

    // Whether a top-level internal class of this assembly can name the type: it and every type it is nested in are
    // public or internal.
    private static bool IsReachable(INamedTypeSymbol type)
    {
        for (ITypeSymbol? t = type; t is not null; t = t.ContainingType)
        {
            if (t.DeclaredAccessibility is not (Accessibility.Public or Accessibility.Internal))
            {
                return false;
            }
        }

        return true;
    }
}
