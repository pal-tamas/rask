using System.Collections.Immutable;
using System.Linq;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Diagnostics;
using Rask.Generators.Shared;

namespace Rask.Generators.Validation;

/// <summary>
///     RASK183 — a value object declares both its own <c>protected override IEnumerable&lt;Problem&gt; Rules()</c> and the
///     in-type FluentValidation <c>static void Rules(InlineValidator&lt;Self&gt; rules)</c>.
/// </summary>
/// <remarks>
///     The generated half of a value object with FluentValidation rules overrides <c>Rules()</c> to run them, so a
///     hand-written override collides with it. Both ways are first-class; one value object keeps one. Silent unless
///     the compilation references FluentValidation.
/// </remarks>
[DiagnosticAnalyzer(LanguageNames.CSharp)]
public sealed class InlineRulesOverrideAnalyzer : DiagnosticAnalyzer
{
    private static readonly DiagnosticDescriptor Rask183 = new(
        "RASK183",
        "A value object declares its rules twice",
        "'{0}' overrides Rules() and declares a static Rules(InlineValidator<{0}>) too — the generated half overrides Rules() to run the FluentValidation rules, so the two collide: keep one",
        DiagnosticHelp.Category,
        DiagnosticSeverity.Error,
        isEnabledByDefault: true,
        description: "A value object states the rules its base record cannot in one of two ways: a hand-written "
                     + "protected override IEnumerable<Problem> Rules(), or FluentValidation's static "
                     + "void Rules(InlineValidator<T> rules), whose generated half overrides Rules() to run them. With "
                     + "both, the record would override Rules() twice. Move the rules into one of them.",
        helpLinkUri: DiagnosticHelp.Link("RASK183"));

    public override ImmutableArray<DiagnosticDescriptor> SupportedDiagnostics { get; } = ImmutableArray.Create(Rask183);

    public override void Initialize(AnalysisContext context)
    {
        context.EnableConcurrentExecution();
        context.ConfigureGeneratedCodeAnalysis(GeneratedCodeAnalysisFlags.None);
        context.RegisterCompilationStartAction(static start =>
        {
            if (start.Compilation.GetTypeByMetadataName(FluentRules.InlineValidatorName) is null)
            {
                return;
            }

            start.RegisterSymbolAction(Analyze, SymbolKind.NamedType);
        });
    }

    private static void Analyze(SymbolAnalysisContext context)
    {
        var type = (INamedTypeSymbol)context.Symbol;
        if (!type.IsRecord || !AggregateShape.IsValueRecord(type))
        {
            return;
        }

        var rules = type.GetMembers(FluentRules.RulesMethod).OfType<IMethodSymbol>().ToList();
        if (!rules.Exists(static m => m is { IsOverride: true, Parameters.Length: 0 } && IsHandWritten(m)) ||
            rules.Find(FluentRules.IsInlineRules) is not { } inline)
        {
            return;
        }

        context.ReportDiagnostic(Diagnostic.Create(Rask183, inline.Locations.FirstOrDefault(), type.Name));
    }

    // Written in the app's own source: the generated half's override, once it exists, is not the collision.
    private static bool IsHandWritten(IMethodSymbol method) =>
        method.DeclaringSyntaxReferences.Any(static r => !IsGenerated(r.SyntaxTree));

    private static bool IsGenerated(SyntaxTree tree) =>
        tree.FilePath.EndsWith(".g.cs", System.StringComparison.OrdinalIgnoreCase) ||
        tree.GetRoot().GetLeadingTrivia().ToString().Contains("<auto-generated");
}
