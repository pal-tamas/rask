#!/usr/bin/env node
// Builds Ui.Phone's engine: ui-phone.ts + intl-tel-input (pinned in package.json, locked in package-lock.json)
// into ONE minified ES module, ../ui-phone.js, and copies the library's own utils (Google's libphonenumber,
// compiled by its authors) beside it as ../ui-phone-utils.js. Both are committed. The kit's build never runs
// this — it needs npm, and the kit builds without Node — so run it by hand after changing ui-phone.ts. The pins
// move daily: scripts/upstream/kit-bundle.mjs phone takes the release fluxui.dev serves and runs this.
//
//     cd src/Rask.Ui/Resources/phone && npm ci && node build.mjs
//
// It also writes ../ui-phone.LICENSES.txt (intl-tel-input's MIT notice, and the Apache-2.0 licence the utils'
// libphonenumber and Closure Library code is under), the versions UiPhoneEngine carries (which UiPhoneTests holds
// to the committed files), and UiPhoneCountries.g.cs: each country's calling code and English name, so a page
// is drawn with the right country before the engine has loaded, and without script at all.
import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { readFile, writeFile, copyFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const kit = join(here, '..', '..');
const library = join(here, 'node_modules', 'intl-tel-input');
const manifest = JSON.parse(await readFile(join(library, 'package.json'), 'utf8'));
const hash = bytes => createHash('sha256').update(bytes).digest('hex').slice(0, 8);

// The utils, as the library ships them: the file fluxui.dev serves is this one.
const utilsOut = join(here, '..', 'ui-phone-utils.js');
await copyFile(join(library, 'dist', 'js', 'utils.js'), utilsOut);
const utilsVersion = hash(await readFile(utilsOut));

const out = join(here, '..', 'ui-phone.js');
await build({
  entryPoints: [join(here, 'ui-phone.ts')],
  outfile: out,
  bundle: true,
  format: 'esm',
  target: 'es2022',
  minify: true,
  legalComments: 'none',
  define: { UTILS: JSON.stringify(`./rask-ui-phone-utils.js?v=${utilsVersion}`) },
  banner: { js: `/*! Rask.Ui phone engine. Bundles intl-tel-input ${manifest.version} (MIT) — see rask-ui-phone.LICENSES.txt, beside this file. */` },
  logLevel: 'warning',
});
const version = hash(await readFile(out));

const section = (title, text) => `\n${'='.repeat(78)}\n${title}\n${'='.repeat(78)}\n${text.trim()}\n`;
let notices = 'Third-party notices of Ui.Phone.\n\n'
  + 'The phone engine (rask-ui-phone.js) bundles intl-tel-input. Its utils (rask-ui-phone-utils.js) are that\n'
  + 'release\'s own build of Google\'s libphonenumber and of the Closure Library code it is compiled with, which\n'
  + 'are under the Apache License 2.0; their copyright lines are kept at the head of each part in that file.\n';
notices += section(`intl-tel-input ${manifest.version} — ${manifest.license}`, await readFile(join(library, 'LICENSE'), 'utf8'));
notices += section('libphonenumber (Copyright (C) 2010 The Libphonenumber Authors) and the Closure Library\n'
  + '(Copyright The Closure Library Authors), in rask-ui-phone-utils.js — Apache-2.0',
  await readFile(join(here, 'notices', 'apache-2.0.txt'), 'utf8'));
await writeFile(join(here, '..', 'ui-phone.LICENSES.txt'), notices);

// The versions, into the class that names the files.
const engine = join(kit, 'UiPhoneEngine.cs');
await writeFile(engine, (await readFile(engine, 'utf8'))
  .replace(/(public const string Version = ")[0-9a-f]*(";)/, `$1${version}$2`)
  .replace(/(public const string UtilsVersion = ")[0-9a-f]*(";)/, `$1${utilsVersion}$2`));

// Every country the library knows, its calling code and its English name, in English alphabetical order.
const data = (await import(join(library, 'dist', 'js', 'data.mjs'))).default;
const names = new Intl.DisplayNames('en', { type: 'region' });
const rows = data.map(c => ({ iso2: c.iso2.toUpperCase(), dial: c.dialCode, name: names.of(c.iso2.toUpperCase()) }));
rows.sort((a, b) => new Intl.Collator('en').compare(a.name, b.name));
const literal = text => '"' + text.replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"';
const table = rows.map(r => `        new(${literal(r.iso2)}, ${literal(r.dial)}, ${literal(r.name)}),`).join('\n');
await writeFile(join(kit, 'UiPhoneCountries.g.cs'), `// <auto-generated>
// Generated by src/Rask.Ui/Resources/phone/build.mjs from intl-tel-input ${manifest.version} (MIT) and the English
// region names of Unicode CLDR (Intl.DisplayNames). Do not edit: change the script and run it.
// </auto-generated>

#nullable enable

namespace Rask;

/// <summary>Every country Ui.Phone knows: its calling code and its English name, in English alphabetical order.</summary>
internal static partial class UiPhoneCountries
{
    /// <summary>The countries, ${rows.length} of them.</summary>
    internal static readonly UiPhoneCountry[] All =
    [
${table}
    ];
}
`);
console.log(`ui-phone.js: version ${version}; ui-phone-utils.js: version ${utilsVersion}; ${rows.length} countries`);
