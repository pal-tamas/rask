using System.Collections.Immutable;
using System.Linq;
using System.Text;
using System.Threading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;
using Rask.Generators.Shared;

namespace Rask.Batteries.Generators;

/// <summary>
///     Registers an aggregate's private <c>void OnDelete()</c>: Rask calls it in every save that deletes the aggregate —
///     the generated <c>X.Delete(id, version)</c>, an editor's delete, a hand <c>Remove</c> and save — before the save's
///     events are read, so what it raises (<c>Raise(new DriverRemoved(Id))</c>) is stored and published with the delete
///     as an operation's events are.
/// </summary>
/// <remarks>RASK190 refuses an <c>OnDelete</c> of another shape, or on an aggregate no part can be added to.</remarks>
[Generator]
public sealed class DeleteHookGenerator : IIncrementalGenerator
{
    internal const string MethodName = "OnDelete";

    internal static readonly DiagnosticDescriptor Rask190 = new(
        "RASK190",
        "An aggregate's OnDelete is not a delete hook",
        "'{0}.OnDelete' {1} — an aggregate's delete hook is 'private void OnDelete()' on a partial aggregate",
        DiagnosticHelp.Category,
        DiagnosticSeverity.Error,
        true,
        description: "A method named OnDelete on an aggregate is what Rask calls when a save deletes it, so the events it "
                     + "raises go out with the delete. That needs a private instance method with no parameters returning "
                     + "void (a public one would be an operation of its own), on a partial, non-generic aggregate declared "
                     + "in a namespace.",
        helpLinkUri: DiagnosticHelp.Link("RASK190"));

    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var hooks = context.SyntaxProvider
            .CreateSyntaxProvider(
                static (node, _) => node is MethodDeclarationSyntax { Identifier.ValueText: MethodName },
                static (ctx, token) => Describe(ctx, token))
            .Where(static hook => hook is not null)
            .Select(static (hook, _) => hook!);

        context.RegisterSourceOutput(hooks.Collect(), static (spc, all) => Emit(spc, all));
    }

    private static Hook? Describe(GeneratorSyntaxContext ctx, CancellationToken token)
    {
        if (ctx.SemanticModel.GetDeclaredSymbol((MethodDeclarationSyntax)ctx.Node, token) is not IMethodSymbol method ||
            method.ContainingType is not { TypeKind: TypeKind.Class } aggregate ||
            !AggregateShape.IsAggregate(aggregate))
        {
            return null;
        }

        return new Hook(
            aggregate.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat),
            aggregate.Name,
            aggregate.ContainingNamespace is { IsGlobalNamespace: false } ns ? ns.ToDisplayString() : "",
            Problem(method) ?? AggregatePart.Problem(aggregate, token),
            SymbolLocation.From(method));
    }

    // Why the method is not 'private void OnDelete()', or null when it is.
    private static string? Problem(IMethodSymbol method)
    {
        if (method.IsStatic)
        {
            return "is static (it is called on the aggregate being deleted)";
        }

        if (method.DeclaredAccessibility != Accessibility.Private)
        {
            return "is not private (a public method of an aggregate is an operation of its own)";
        }

        if (method.IsGenericMethod || method.Parameters.Length > 0)
        {
            return "takes parameters";
        }

        return method.ReturnsVoid ? null : $"returns '{method.ReturnType.ToDisplayString()}', not void";
    }

    private static void Emit(SourceProductionContext context, ImmutableArray<Hook> all)
    {
        // Distinct: one aggregate declares one OnDelete(); a second is a compile error of its own.
        foreach (var hook in all.Distinct().OrderBy(static h => h.AggregateFqn, System.StringComparer.Ordinal))
        {
            if (hook.Refused is { } refused)
            {
                context.ReportDiagnostic(Diagnostic.Create(Rask190, hook.Location?.ToLocation(), hook.AggregateName, refused));
                continue;
            }

            context.AddSource(hook.AggregateFqn.Replace("global::", "") + ".OnDelete.g.cs", SourceText.From(Render(hook), Encoding.UTF8));
        }
    }

    private static string Render(Hook hook)
    {
        var s = new StringBuilder();
        s.AppendLine("// <auto-generated/>");
        s.AppendLine("#nullable enable");
        s.AppendLine();
        if (hook.Namespace.Length > 0)
        {
            s.Append("namespace ").Append(hook.Namespace).AppendLine(";");
            s.AppendLine();
        }

        s.Append("partial class ").AppendLine(hook.AggregateName);
        s.AppendLine("{");
        s.AppendLine("    /// <summary>Registers this aggregate's <c>OnDelete()</c>, called by every save that deletes it.</summary>");
        s.AppendLine("    [global::System.Runtime.CompilerServices.ModuleInitializer]");
        s.AppendLine("    [global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]");
        s.AppendLine("    internal static void __RaskRegisterOnDelete() =>");
        s.Append("        global::Rask.Data.DeleteHooks.Register(typeof(").Append(hook.AggregateFqn)
            .Append("), static aggregate => ((").Append(hook.AggregateFqn).Append(")aggregate).").Append(MethodName).AppendLine("());");
        s.AppendLine("}");
        return s.ToString();
    }

    private sealed record Hook(string AggregateFqn, string AggregateName, string Namespace, string? Refused, SymbolLocation? Location);
}
