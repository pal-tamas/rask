using System;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;
using Rask.Generators.Shared;

namespace Rask.Batteries.Generators;

/// <summary>
/// Finds the app's one <c>Rask.Data.IRaskModel</c> — the class holding its model-wide rules — and emits a
/// <c>[ModuleInitializer]</c> naming it to <c>Rask.Data.ModelRegistry</c>, so every context built from the registry
/// applies them with nothing registered.
/// </summary>
[Generator]
public sealed class RaskModelGenerator : IIncrementalGenerator
{
    private const string Interface = "Rask.Data.IRaskModel";

    private static readonly DiagnosticDescriptor Rask110 = new(
        "RASK110",
        "More than one IRaskModel",
        "'{0}' and '{1}' both implement IRaskModel, so Rask cannot tell which rules this app's model is built under; "
        + "keep one and move the other's rules into it",
        DiagnosticHelp.Category,
        DiagnosticSeverity.Error,
        true,
        description: "The app-wide model rules are found rather than registered, which needs there to be one class "
                     + "holding them. With two, applying either would build a schema the other one's rules disagree "
                     + "with — a string length, a constraint name — and the difference would surface as a migration "
                     + "nobody meant to write.",
        helpLinkUri: DiagnosticHelp.Link("RASK110"));

    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var candidates = context.SyntaxProvider
            .CreateSyntaxProvider(
                static (node, _) => node is ClassDeclarationSyntax { BaseList.Types.Count: > 0 },
                static (ctx, _) => GetCandidate(ctx))
            .Where(static c => c is not null)
            .Select(static (c, _) => c!.Value);

        context.RegisterSourceOutput(candidates.Collect(), static (spc, all) => Emit(spc, all));
    }

    private static Candidate? GetCandidate(GeneratorSyntaxContext ctx)
    {
        if (ctx.Node is not ClassDeclarationSyntax declaration ||
            ctx.SemanticModel.GetDeclaredSymbol(declaration) is not INamedTypeSymbol symbol ||
            symbol.IsAbstract || symbol.IsGenericType ||
            !symbol.AllInterfaces.Any(static i => i.ToDisplayString() is Interface))
        {
            return null;
        }

        return new Candidate(
            symbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat),
            SymbolLocation.From(symbol));
    }

    private static void Emit(SourceProductionContext context, ImmutableArray<Candidate> candidates)
    {
        if (candidates.IsDefaultOrEmpty)
        {
            return;
        }

        // Distinct because a partial class contributes one candidate per declaration.
        var models = candidates
            .Distinct()
            .OrderBy(static c => c.FullyQualifiedName, StringComparer.Ordinal)
            .ToList();

        if (models.Count > 1)
        {
            context.ReportDiagnostic(Diagnostic.Create(
                Rask110,
                models[1].Location?.ToLocation(),
                models[0].FullyQualifiedName,
                models[1].FullyQualifiedName));
            return;
        }

        var source = new StringBuilder();
        source.AppendLine("// <auto-generated/>");
        source.AppendLine("#nullable enable");
        source.AppendLine();
        source.AppendLine("namespace Rask.Data.Generated;");
        source.AppendLine();
        source.AppendLine("/// <summary>Names this app's model-wide rules to Rask.Data.</summary>");
        source.AppendLine("internal static class __RaskModel");
        source.AppendLine("{");
        source.AppendLine("    [global::System.Runtime.CompilerServices.ModuleInitializer]");
        source.Append("    internal static void Initialize() => global::Rask.Data.ModelRegistry.UseModel<")
            .Append(models[0].FullyQualifiedName).AppendLine(">();");
        source.AppendLine("}");

        context.AddSource("__RaskModel.g.cs", SourceText.From(source.ToString(), Encoding.UTF8));
    }

    private readonly record struct Candidate(string FullyQualifiedName, SymbolLocation? Location);
}
