using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;

namespace Rask.Batteries.Generators;

public sealed partial class ValueObjectFactoryGenerator
{
    private static string Render(ValueObject value)
    {
        var s = new StringBuilder();
        s.AppendLine("// <auto-generated/>");
        s.AppendLine("#nullable enable");
        s.AppendLine();

        if (value.Namespace.Length > 0)
        {
            s.Append("namespace ").Append(value.Namespace).AppendLine(";");
            s.AppendLine();
        }

        foreach (var container in value.Containers)
        {
            s.AppendLine(container);
            s.AppendLine("{");
        }

        s.Append("partial record ").AppendLine(value.Name);
        s.AppendLine("{");
        AppendCreate(s, value);
        AppendTryCreate(s, value);
        AppendCreateOptional(s, value);
        if (value.OneValue)
        {
            AppendProblems(s, value);
        }

        AppendFacets(s, value);
        AppendField(s, value);
        s.AppendLine("}");

        foreach (var _ in value.Containers)
        {
            s.AppendLine("}");
        }

        return s.ToString();
    }

    private static string Declared(ValueObject value) =>
        string.Join(", ", value.Parameters.Select(static p => p.Type + " " + p.Name));

    private static string Names(ValueObject value) => string.Join(", ", value.Parameters.Select(static p => p.Name));

    private static void AppendCreate(StringBuilder s, ValueObject value)
    {
        var name = value.Name;
        s.Append("    /// <summary>A <see cref=\"").Append(name).AppendLine("\" />, once its rules accept it.</summary>");
        s.AppendLine("    /// <param name=\"field\">The field it came from, as a form names it: a refusal is shown under it, a member's under <c>field.Member</c>.</param>");
        s.AppendLine("    /// <exception cref=\"global::Rask.Cqrs.RaskValidationException\">A rule refuses it.</exception>");
        s.Append("    public static ").Append(name).Append(" Create(").Append(Declared(value)).AppendLine(", string? field = null) =>");
        s.Append("        TryCreate(").Append(Names(value)).Append(", out var __made, out var __problems) ? __made : throw ")
            .Append(Rules).AppendLine(".Refused(__problems, field);");
        s.AppendLine();
    }

    private static void AppendTryCreate(StringBuilder s, ValueObject value)
    {
        var name = value.Name;
        s.Append("    /// <summary>A <see cref=\"").Append(name).AppendLine("\" />, or what its rules say against it — never an exception for a refusal.</summary>");
        s.Append("    public static bool TryCreate(").Append(Declared(value))
            .Append(", [global::System.Diagnostics.CodeAnalysis.NotNullWhen(true)] out ").Append(name).Append("? result, out ")
            .Append(ProblemList).AppendLine(" problems)");
        s.AppendLine("    {");
        s.Append("        using var __attempt = ").Append(Rules).AppendLine(".Attempt();");
        s.Append("        var __made = new ").Append(name).Append('(').Append(Names(value)).AppendLine(");");
        s.AppendLine("        problems = __attempt.Problems;");
        s.AppendLine("        result = problems.Count == 0 ? __made : null;");
        s.AppendLine("        return result is not null;");
        s.AppendLine("    }");
        s.AppendLine();
    }

    // Nothing when nothing was given (text: only blanks); a Required failure under each member that may not be
    // empty when only some were; otherwise Create.
    private static void AppendCreateOptional(StringBuilder s, ValueObject value)
    {
        var name = value.Name;
        var optional = string.Join(", ", value.Parameters.Select(static p => p.OptionalType + " " + p.Name));
        var passed = string.Join(", ", value.Parameters.Select(Given));

        s.Append("    /// <summary>Nothing for a value left ").Append(value.Parameters.Any(static p => p.IsText) ? "blank" : "empty")
            .AppendLine("; otherwise <see cref=\"Create\" />.</summary>");
        s.AppendLine("    /// <exception cref=\"global::Rask.Cqrs.RaskValidationException\">Only some of it is given, or a rule refuses it.</exception>");
        s.Append("    public static ").Append(name).Append("? CreateOptional(").Append(optional).AppendLine(", string? field = null)");
        s.AppendLine("    {");
        s.Append("        if (").Append(string.Join(" && ", value.Parameters.Select(Empty))).AppendLine(")");
        s.AppendLine("        {");
        s.AppendLine("            return null;");
        s.AppendLine("        }");
        s.AppendLine();

        var required = value.Parameters.Where(static p => !p.Nullable).ToList();
        if (value.Parameters.Count > 1 && required.Count > 0)
        {
            s.Append("        global::System.Collections.Generic.List<").Append(ProblemType).AppendLine(">? __missing = null;");
            foreach (var parameter in required)
            {
                s.Append("        if (").Append(Empty(parameter)).AppendLine(")");
                s.AppendLine("        {");
                s.Append("            (__missing ??= []).Add(").Append(Rules).Append(".Missing(\"").Append(parameter.Name).AppendLine("\"));");
                s.AppendLine("        }");
                s.AppendLine();
            }

            s.AppendLine("        if (__missing is not null)");
            s.AppendLine("        {");
            s.Append("            throw ").Append(Rules).AppendLine(".Refused(__missing, field);");
            s.AppendLine("        }");
            s.AppendLine();
        }

        s.Append("        return Create(").Append(passed).AppendLine(", field);");
        s.AppendLine("    }");
    }

    private static string Empty(Parameter parameter) =>
        parameter.IsText ? "string.IsNullOrWhiteSpace(" + parameter.Name + ")" : parameter.Name + " is null";

    // The optional parameter handed on to Create, as the type Create takes.
    private static string Given(Parameter parameter)
    {
        if (parameter.Nullable)
        {
            return parameter.Name;
        }

        return parameter.IsValueType ? parameter.Name + ".GetValueOrDefault()" : parameter.Name + "!";
    }

    private static void AppendProblems(StringBuilder s, ValueObject value)
    {
        var held = value.Parameters[0];
        s.AppendLine();
        s.AppendLine("    /// <summary>What the rules say against <paramref name=\"value\" />: what a form and a generated write ask.</summary>");
        s.AppendLine(Hidden);
        s.Append("    public static ").Append(Messages).Append(" __Problems(").Append(held.OptionalType).AppendLine(" value)");
        s.AppendLine("    {");
        if (held.IsValueType)
        {
            s.AppendLine("        if (value is not { } __given)");
            s.AppendLine("        {");
            s.Append("            return ").Append(Rules).AppendLine(".Required();");
            s.AppendLine("        }");
            s.AppendLine();
            s.AppendLine("        TryCreate(__given, out _, out var __problems);");
        }
        else
        {
            s.AppendLine("        TryCreate(value!, out _, out var __problems);");
        }

        s.Append("        return ").Append(Rules).AppendLine(".Messages(__problems);");
        s.AppendLine("    }");
    }

    // What the column is given — read when the app was compiled, so no instance (and no rule) is asked for it.
    private static void AppendFacets(StringBuilder s, ValueObject value)
    {
        if (value.ValueBase is not ("Text" or "Number"))
        {
            return;
        }

        var facets = value.Facets;
        var named = new List<string>();
        AddFacet(named, "MaxLength", facets.MaxLength);
        AddFacet(named, "Precision", facets.Precision);
        AddFacet(named, "Scale", facets.Scale);

        s.AppendLine();
        s.AppendLine("    /// <summary>The length, precision and scale it declares: what its column is given.</summary>");
        s.AppendLine(Hidden);
        s.Append("    public static global::Rask.Data.ValueFacets __Facets => new(").Append(string.Join(", ", named)).AppendLine(");");
    }

    private static void AddFacet(List<string> named, string name, int? value)
    {
        if (value is { } given)
        {
            named.Add(name + ": " + given.ToString(CultureInfo.InvariantCulture));
        }
    }

    // Hands Rask's strings catalog to Rask.Data's ValueWords as the assembly loads: the bases' rules are then said
    // in the reader's language.
    private static string RenderWords()
    {
        const string Strings = "global::Rask.Core.Globalization.RaskStrings";
        const string Keys = "global::Rask.Core.Globalization.RaskString";
        const string Kinds = "global::Rask.Data.ValueProblemKind";

        var s = new StringBuilder();
        s.AppendLine("// <auto-generated/>");
        s.AppendLine("#nullable enable");
        s.AppendLine();
        s.AppendLine("/// <summary>Words the rules of Rask.Data's value-object bases from Rask's strings catalog.</summary>");
        s.AppendLine("file static class __RaskValueWords");
        s.AppendLine("{");
        s.AppendLine("    [global::System.Runtime.CompilerServices.ModuleInitializer]");
        s.AppendLine("    internal static void Use() => global::Rask.Data.ValueWords.Use(Say);");
        s.AppendLine();
        s.AppendLine("    private static string Say(global::Rask.Data.ValueProblem problem) =>");
        s.AppendLine("        problem.Kind switch");
        s.AppendLine("        {");
        foreach (var (kind, key, limit) in Sentences)
        {
            s.Append("            ").Append(Kinds).Append('.').Append(kind).Append(" => ").Append(Strings).Append(".Get(")
                .Append(Keys).Append('.').Append(key).Append(", problem.Template").Append(limit ? ", problem.Limit" : "").AppendLine("),");
        }

        s.AppendLine("            _ => problem.English,");
        s.AppendLine("        };");
        s.AppendLine("}");
        return s.ToString();
    }

    // Each rule a base can break, and the catalog key that words it.
    private static readonly (string Kind, string Key, bool Limit)[] Sentences =
    [
        ("Required", "ValidationRequired", false),
        ("TooShort", "ValidationTooShort", true),
        ("TooLong", "ValidationTooLong", true),
        ("Pattern", "ValidationPattern", false),
        ("BelowMin", "ValidationNumberMin", true),
        ("AboveMax", "ValidationNumberMax", true),
        ("TooManyDecimals", "ValidationDecimals", true),
        ("TooManyDigits", "ValidationNumberRange", false),
        ("BeforeEarliest", "ValidationDateMin", true),
        ("AfterLatest", "ValidationDateMax", true),
        ("EndBeforeStart", "ValidationRangeNotBefore", true),
        ("EndNotAfterStart", "ValidationRangeAfter", true),
    ];
}
