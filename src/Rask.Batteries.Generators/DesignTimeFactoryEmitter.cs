using System.Text;

namespace Rask.Batteries.Generators;

/// <summary>Writes the design-time factory <see cref="DesignTimeFactoryGenerator" /> generates for one context.</summary>
/// <remarks>
/// The factory decides nothing itself. It reads the configuration the app starts with, the way
/// <c>WebApplication.CreateBuilder</c> reads it, and hands it to <c>UseRaskDatabase</c> — the call the app's own
/// registration makes — so the provider, its <c>Rask:Sqlite</c>/<c>Rask:Postgres</c>/<c>Rask:SqlServer</c> tuning and
/// Rask's migration conventions are the app's, and an unknown provider or a missing connection string fails with the
/// sentence the app itself would start with.
/// </remarks>
internal static class DesignTimeFactoryEmitter
{
    internal const string ProviderKey = "Rask:Database:Provider";

    /// <summary>The factory's source.</summary>
    /// <param name="context">The context it builds.</param>
    /// <param name="providerRequired">
    /// Whether the context is registered with <c>AddRaskData&lt;T&gt;(…)</c> through a callback that names its
    /// own provider: there SQLite is no default to fall back on, so an unset <c>Rask:Database:Provider</c> stops the
    /// tool rather than writing migrations for a database the app does not open.
    /// </param>
    internal static string Emit(DesignTimeContext context, bool providerRequired)
    {
        var source = new StringBuilder();
        source.AppendLine("// <auto-generated/>");
        source.AppendLine("#nullable enable");
        source.AppendLine();

        var indent = string.Empty;
        if (context.Namespace.Length > 0)
        {
            source.Append("namespace ").AppendLine(context.Namespace);
            source.AppendLine("{");
            indent = "    ";
        }

        WriteFactory(source, indent, context, providerRequired);

        if (context.Namespace.Length > 0)
        {
            source.AppendLine("}");
        }

        return source.ToString();
    }

    private static void WriteFactory(StringBuilder source, string indent, DesignTimeContext context, bool providerRequired)
    {
        var type = context.FullyQualifiedName;
        source.Append(indent).AppendLine("/// <summary>");
        source.Append(indent).Append("/// Builds <c>").Append(context.DisplayName)
            .AppendLine("</c> for <c>dotnet ef</c> from the app's configuration, without running its Program.cs: the database")
            .Append(indent).AppendLine("/// <c>Rask:Database:Provider</c> names, at <c>Rask:ConnectionStrings:App</c>, through <c>UseRaskDatabase</c>.");
        source.Append(indent).Append("/// An <c>IDesignTimeDbContextFactory&lt;").Append(context.DisplayName)
            .AppendLine("&gt;</c> of the app's own replaces it.");
        source.Append(indent).AppendLine("/// </summary>");
        source.Append(indent).AppendLine("[global::System.CodeDom.Compiler.GeneratedCode(\"Rask.Batteries.Generators\", \"1.0.0\")]");
        source.Append(indent).Append("internal sealed class ").Append(context.FactoryName)
            .Append(" : global::Microsoft.EntityFrameworkCore.Design.IDesignTimeDbContextFactory<").Append(type).AppendLine(">");
        source.Append(indent).AppendLine("{");
        source.Append(indent).Append("    public ").Append(type).AppendLine(" CreateDbContext(string[] args)");
        source.Append(indent).AppendLine("    {");
        source.Append(indent).AppendLine("        // What the app starts with: appsettings.json, appsettings.{Environment}.json, the user secrets in Development,");
        source.Append(indent).AppendLine("        // the environment (Rask__Database__Provider) and the command line, in WebApplication's order. Named after this");
        source.Append(indent).AppendLine("        // assembly, because the entry assembly under dotnet ef is the tool's, which has no user secrets.");
        source.Append(indent).AppendLine("        var configuration = global::Microsoft.AspNetCore.Builder.WebApplication.CreateBuilder(");
        source.Append(indent).AppendLine("            new global::Microsoft.AspNetCore.Builder.WebApplicationOptions");
        source.Append(indent).AppendLine("            {");
        source.Append(indent).AppendLine("                Args = args,");
        source.Append(indent).Append("                ApplicationName = typeof(").Append(type).AppendLine(").Assembly.GetName().Name,");
        source.Append(indent).AppendLine("            }).Configuration;");

        if (providerRequired)
        {
            WriteProviderCheck(source, indent, context);
        }

        source.AppendLine();
        source.Append(indent).AppendLine("        var services = new global::Microsoft.Extensions.DependencyInjection.ServiceCollection();");
        source.Append(indent).AppendLine("        global::Microsoft.Extensions.DependencyInjection.ServiceCollectionServiceExtensions");
        source.Append(indent).AppendLine("            .AddSingleton<global::Microsoft.Extensions.Configuration.IConfiguration>(services, configuration);");
        source.AppendLine();
        source.Append(indent).AppendLine("        var options = global::Rask.RaskDatabaseDbContextOptionsExtensions.UseRaskDatabase(");
        source.Append(indent).Append("            new global::Microsoft.EntityFrameworkCore.DbContextOptionsBuilder<").Append(type).AppendLine(">(),");
        source.Append(indent).AppendLine("            global::Microsoft.Extensions.DependencyInjection.ServiceCollectionContainerBuilderExtensions.BuildServiceProvider(services));");
        source.Append(indent).Append("        return new ").Append(type).AppendLine("(options.Options);");
        source.Append(indent).AppendLine("    }");
        source.Append(indent).AppendLine("}");
    }

    private static void WriteProviderCheck(StringBuilder source, string indent, DesignTimeContext context)
    {
        var name = context.DisplayName;
        source.AppendLine();
        source.Append(indent).Append("        if (string.IsNullOrWhiteSpace(configuration[\"").Append(ProviderKey).AppendLine("\"]))");
        source.Append(indent).AppendLine("        {");
        source.Append(indent).AppendLine("            throw new global::System.InvalidOperationException(");
        source.Append(indent).Append("                \"").Append(ProviderKey).Append(" is not set, so dotnet ef cannot tell which database ")
            .Append(name).Append("'s migrations are for: AddRaskData<").Append(name)
            .AppendLine("> chooses it in Program.cs, which a design-time factory does not run. \"");
        source.Append(indent)
            .AppendLine("                + \"Set it to sqlite, postgres or sqlserver (Rask__Database__Provider in the environment), with the connection string at \"");
        source.Append(indent).Append("                + \"Rask:ConnectionStrings:App, or write an IDesignTimeDbContextFactory<").Append(name)
            .AppendLine("> of your own, which replaces this one.\");");
        source.Append(indent).AppendLine("        }");
    }
}
