using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using System.Threading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;
using Rask.Generators.Shared;

namespace Rask.Batteries.Generators;

/// <summary>
/// Writes the generated half of an entity keyed by several columns — <c>Entity&lt;(DeliveryNote, Transaction)&gt;</c>:
/// a <c>{Aggregate}Id</c> for each aggregate the key names, and an <c>Id</c> that is the key's values together.
/// </summary>
/// <remarks>
/// The tuple names TYPES, so the key reads as what the row is — the pair of a delivery note and a transaction — and
/// each column's type is that aggregate's own key type, never restated. A scalar part, <c>(Order, int LineNo)</c>, is
/// a property the entity declares itself.
/// </remarks>
[Generator]
public sealed class CompositeKeyGenerator : IIncrementalGenerator
{
    internal static readonly DiagnosticDescriptor Rask105 = new(
        "RASK105",
        "A key of several columns cannot be built",
        "'{0}' has a key of several columns, but {1}",
        DiagnosticHelp.Category,
        DiagnosticSeverity.Error,
        true,
        description: "Entity<(DeliveryNote, Transaction)> keys a child row by the aggregates it joins: Rask generates "
                     + "a DeliveryNoteId and a TransactionId of those aggregates' key types, and an Id that is the "
                     + "two values together. That needs a partial class it can add to, parts it can name, and names "
                     + "nothing else holds. Writing such a row through its aggregate is not supported yet, so a form "
                     + "that would carry one is refused here rather than half-written.",
        helpLinkUri: DiagnosticHelp.Link("RASK105"));

    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var keys = context.SyntaxProvider
            .CreateSyntaxProvider(
                static (node, _) => node is ClassDeclarationSyntax { BaseList.Types.Count: > 0 },
                static (ctx, token) => Describe(ctx, token))
            .Where(static key => key is not null)
            .Select(static (key, _) => key!);

        context.RegisterSourceOutput(keys.Collect(), static (spc, all) => Emit(spc, all));
    }

    private static Key? Describe(GeneratorSyntaxContext ctx, CancellationToken token)
    {
        if (ctx.Node is not ClassDeclarationSyntax declaration ||
            ctx.SemanticModel.GetDeclaredSymbol(declaration, token) is not INamedTypeSymbol entity ||
            !AggregateShape.IsMappedEntity(entity) ||
            !CompositeKeyShape.HasCompositeKey(entity))
        {
            return null;
        }

        var problems = new List<string>();
        var parts = CompositeKeyShape.PartsOf(entity, problems);
        CompositeKeyShape.AddDeclarationProblems(entity, parts, problems);

        return new Key(
            entity.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat),
            entity.Name,
            entity.ContainingNamespace is { IsGlobalNamespace: false } ns ? ns.ToDisplayString() : "",
            new EquatableArray<Part>([.. parts.Select(static p => new Part(
                p.Name,
                p.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat),
                p.Aggregate?.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)))]),
            new EquatableArray<string>([.. problems]),
            SymbolLocation.From(entity));
    }

    private static void Emit(SourceProductionContext context, ImmutableArray<Key> all)
    {
        // Distinct because a partial class contributes one key per declaration.
        foreach (var key in all.Distinct().OrderBy(static k => k.FullyQualifiedName, System.StringComparer.Ordinal))
        {
            if (key.Problems.Count > 0)
            {
                foreach (var problem in key.Problems)
                {
                    context.ReportDiagnostic(Diagnostic.Create(Rask105, key.Location?.ToLocation(), key.Name, problem));
                }

                continue;
            }

            context.AddSource(
                key.FullyQualifiedName.Replace("global::", "") + ".Key.g.cs",
                SourceText.From(Render(key), Encoding.UTF8));
        }
    }

    private static string Render(Key key)
    {
        var s = new StringBuilder();
        s.AppendLine("// <auto-generated/>");
        s.AppendLine("#nullable enable");
        s.AppendLine();

        if (key.Namespace.Length > 0)
        {
            s.Append("namespace ").Append(key.Namespace).AppendLine(";");
            s.AppendLine();
        }

        s.Append("partial class ").AppendLine(key.Name);
        s.AppendLine("{");

        foreach (var part in key.Parts.Where(static p => p.Aggregate is not null))
        {
            s.Append("    /// <summary>The <see cref=\"").Append(part.Aggregate)
                .AppendLine("\" /> this row belongs to: a part of its key.</summary>");
            s.Append("    public ").Append(part.TypeName).Append(' ').Append(part.Name)
                .AppendLine(" { get; private set; }");
            s.AppendLine();
        }

        s.AppendLine("    /// <summary>The key: its parts' values, in the order the declaration names them.</summary>");
        s.Append("    public new (")
            .Append(string.Join(", ", key.Parts.Select(static p => p.TypeName + " " + p.Name)))
            .Append(") Id => (")
            .Append(string.Join(", ", key.Parts.Select(static p => p.Name)))
            .AppendLine(");");
        s.AppendLine("}");

        return s.ToString();
    }

    private sealed record Part(string Name, string TypeName, string? Aggregate);

    private sealed record Key(
        string FullyQualifiedName,
        string Name,
        string Namespace,
        EquatableArray<Part> Parts,
        EquatableArray<string> Problems,
        SymbolLocation? Location);
}
