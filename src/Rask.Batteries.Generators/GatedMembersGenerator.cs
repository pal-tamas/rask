using System;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using System.Threading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Rask.Batteries.Generators;

/// <summary>
///     Declares, at startup, every member an entity's <c>Configure</c> gates — <c>b.Gated(d =&gt; d.Card, Module.Tachograph)</c>
///     — so a form and a read face know it is gated before the EF model is first built (<c>Rask.Data.GeneratedGates</c>).
/// </summary>
/// <remarks>
///     A gate is taken as written when it is a constant (an enum member) or a static field or property the assembly can
///     reach; any other is declared when the model is built, as before.
/// </remarks>
[Generator]
public sealed class GatedMembersGenerator : IIncrementalGenerator
{
    private const string GatedExtensions = "Rask.Data.GatedBuilderExtensions";

    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var declared = context.SyntaxProvider
            .CreateSyntaxProvider(
                static (node, _) => node is InvocationExpressionSyntax
                {
                    Expression: MemberAccessExpressionSyntax { Name.Identifier.ValueText: "Gated" },
                    ArgumentList.Arguments.Count: 2,
                },
                static (ctx, ct) => Declaration(ctx, ct))
            .Where(static d => d is not null)
            .Select(static (d, _) => d!);

        var canDeclare = context.CompilationProvider.Select(static (c, _) =>
            c.GetTypeByMetadataName("Rask.Data.GeneratedGates")?.GetMembers("Declare").Length > 0);

        context.RegisterSourceOutput(declared.Collect().Combine(canDeclare), static (spc, pair) => Emit(spc, pair.Left, pair.Right));
    }

    private static GatedDeclaration? Declaration(GeneratorSyntaxContext ctx, CancellationToken cancellationToken)
    {
        var call = (InvocationExpressionSyntax)ctx.Node;
        if (ctx.SemanticModel.GetSymbolInfo(call, cancellationToken).Symbol is not IMethodSymbol
            {
                Name: "Gated",
                ReducedFrom: { } extension,
                TypeArguments.Length: 3,
            } gated ||
            gated.TypeArguments[0] is not INamedTypeSymbol entity ||
            !string.Equals(extension.ContainingType.ToDisplayString(), GatedExtensions, StringComparison.Ordinal) ||
            call.ArgumentList.Arguments[0].Expression is not LambdaExpressionSyntax { Body: MemberAccessExpressionSyntax member } ||
            GateOf(call.ArgumentList.Arguments[1].Expression, ctx.SemanticModel, cancellationToken) is not { } gate)
        {
            return null;
        }

        return new GatedDeclaration(entity.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat), member.Name.Identifier.ValueText, gate);
    }

    // The gate as C# the module initializer can write: an enum's constant, or a static member the assembly reaches.
    private static string? GateOf(ExpressionSyntax gate, SemanticModel model, CancellationToken cancellationToken)
    {
        var type = model.GetTypeInfo(gate, cancellationToken).Type;
        var constant = model.GetConstantValue(gate, cancellationToken);
        if (constant.HasValue && type is { TypeKind: TypeKind.Enum } && constant.Value is not null)
        {
            return "(" + type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) + ")(" +
                   SymbolDisplay.FormatPrimitive(constant.Value, quoteStrings: true, useHexadecimalNumbers: false) + ")";
        }

        if (constant is { HasValue: true, Value: string text })
        {
            return SymbolDisplay.FormatLiteral(text, quote: true);
        }

        return model.GetSymbolInfo(gate, cancellationToken).Symbol is { IsStatic: true, Kind: SymbolKind.Field or SymbolKind.Property } held &&
               held.DeclaredAccessibility is Accessibility.Public or Accessibility.Internal &&
               held.ContainingType.DeclaredAccessibility is Accessibility.Public or Accessibility.Internal
            ? held.ContainingType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) + "." + held.Name
            : null;
    }

    private static void Emit(SourceProductionContext context, ImmutableArray<GatedDeclaration> all, bool canDeclare)
    {
        if (!canDeclare || all.IsDefaultOrEmpty)
        {
            return;
        }

        var s = new StringBuilder();
        s.AppendLine("// <auto-generated/>");
        s.AppendLine("#nullable enable");
        s.AppendLine("namespace Rask.Data.Generated;");
        s.AppendLine();
        s.AppendLine("file static class __RaskGatedMembers");
        s.AppendLine("{");
        s.AppendLine("    [global::System.Runtime.CompilerServices.ModuleInitializer]");
        s.AppendLine("    internal static void Declare()");
        s.AppendLine("    {");
        foreach (var gated in all.Distinct().OrderBy(static g => g.Entity + "." + g.Member, StringComparer.Ordinal))
        {
            s.Append("        global::Rask.Data.GeneratedGates.Declare(typeof(").Append(gated.Entity).Append("), ")
                .Append(SymbolDisplay.FormatLiteral(gated.Member, quote: true)).Append(", ").Append(gated.Gate).AppendLine(");");
        }

        s.AppendLine("    }");
        s.AppendLine("}");
        context.AddSource("__RaskGatedMembers.g.cs", SourceText.From(s.ToString(), Encoding.UTF8));
    }

    private sealed record GatedDeclaration(string Entity, string Member, string Gate);
}
