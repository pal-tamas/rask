using System.Text;

namespace Rask.Cli.Scaffolding;

// The native template: a WebView-hybrid iOS + Android app.
internal static partial class ProjectGenerator
{
    /// <summary>
    /// Generates the <c>native</c> template into <paramref name="targetDirectory"/>. <paramref name="host"/>
    /// names which of Rask's app models supplies the UI: <c>"native"</c> (the Rask component code runs
    /// in-process on the device — offline, store-distributable), or <c>"server"</c> / <c>"wasm-hosted"</c>,
    /// a thin native shell over a Rask app you host, named for which kind it points at.
    /// </summary>
    public static ScaffoldResult GenerateNative(
        string targetDirectory, string name, string host, string version, bool ios = true, bool android = true)
    {
        // Neither platform is a project with nothing in it, so an empty selection is read as "both" rather
        // than scaffolded literally. The command line rejects it before this; this is the belt.
        if (!ios && !android)
        {
            (ios, android) = (true, true);
        }

        // "native" is the on-device model: the whole app runs in-process. Anything else is a thin shell over
        // a Rask app you host. The two remote models ("server", "wasm-hosted") scaffold the same heads —
        // RaskServerWebView is handed a trusted origin and never asks what serves it — and differ only in the
        // guidance baked into the file.
        var isLocal = NativeModels.For(host).RunsInProcess;

        // The csproj, plus each selected platform's manifest and entry point. An unselected platform
        // contributes no TFM and no files at all — a Platforms/iOS folder in an Android-only app is code
        // that never compiles and never runs, which is the kind of thing people keep around for years.
        var files = new List<(string Path, string Content)>
        {
            ($"{NameToken}.csproj", NativeCsproj(version, ios, android)),
        };

        if (android)
        {
            // The Android manifest carries an inline IsLocal conditional (the notification permission the
            // native backends need) resolved per host — see NativeAndroidManifest.
            files.Add(("Platforms/Android/AndroidManifest.xml", NativeAndroidManifest(isLocal)));
        }

        if (ios)
        {
            files.Add(("Platforms/iOS/Info.plist", NativeInfoPlist(isLocal)));
            files.Add(("Platforms/iOS/Main.cs", NativeMainCs));
        }

        if (isLocal)
        {
            // Native + Local: the component tree (App shell in Features/Shared, welcome screen in Features/Home)
            // plus the in-process platform heads, each of which boots a NativeAppHost + RunLocalAsync<App>.
            files.Add(("Features/Shared/App.cs", NativeAppShell));
            files.Add(("Features/Home/HomePage.cs", NativeHomePage));

            if (ios)
            {
                files.Add(("Platforms/iOS/AppDelegate.cs", NativeIosAppDelegate));
            }

            if (android)
            {
                files.Add(("Platforms/Android/MainActivity.cs", NativeAndroidMainActivity));
            }
        }
        else
        {
            // Native + remote: a thin shell — just the platform heads that point RaskServerWebView at a
            // Rask app you host. No shared component code runs on the device.
            if (ios)
            {
                files.Add(("Platforms/iOS/ServerAppDelegate.cs", NativeIosServerAppDelegate(host)));
            }

            if (android)
            {
                files.Add(("Platforms/Android/ServerActivity.cs", NativeAndroidServerActivity(host)));
            }
        }

        if (!isLocal)
        {
            // A remote model scaffolds BOTH halves — the app the shell points at, and the heads — as one
            // solution. A shell with nothing behind it is not a runnable app, and "runnable from the first
            // command" is the DX the four models are supposed to share.
            return GenerateNativeWithApp(targetDirectory, name, host, version, files, ios, android);
        }

        files.AddRange(ProjectHygiene($"{NameToken}.csproj"));

        var scaffoldFiles = Materialize(targetDirectory, name, files);

        return new ScaffoldResult(scaffoldFiles, NativeNextSteps(name, host, ios, android))
        {
            Packages = ["Rask.Native"],
        };
    }

    /// <summary>
    /// The remote models (<c>server</c>, <c>wasm-hosted</c>) as one solution: the Rask app you host, plus a
    /// <c>{name}.Mobile</c> project carrying the platform heads that point at it.
    /// </summary>
    /// <remarks>
    /// The app half is generated by the SAME generator the standalone template uses, into its own
    /// subdirectory and under its own name — <c>Materialize</c> substitutes the placeholder in paths and
    /// namespaces alike, so passing <c>{name}.Server</c> yields <c>{name}.Server/{name}.Server.csproj</c> with
    /// <c>{name}.Server.Features.*</c> namespaces, with no duplicated template content and nothing to drift.
    /// Its per-solution hygiene is dropped and re-emitted once at the root, over every project.
    /// </remarks>
    private static ScaffoldResult GenerateNativeWithApp(
        string targetDirectory,
        string name,
        string host,
        string version,
        List<(string Path, string Content)> mobileFiles,
        bool ios,
        bool android)
    {
        var wasmHosted = string.Equals(host, "wasm-hosted", StringComparison.Ordinal);

        // wasm-hosted is already a multi-project solution, so its three projects sit at the root beside the
        // mobile head; server is a single project and gets a `.Server` directory of its own, which also gives
        // the two models the same project name for the same role.
        var app = wasmHosted
            ? GenerateWasmHosted(targetDirectory, name, new ServerBatteries(), version)
            : GenerateServer(
                System.IO.Path.Combine(targetDirectory, $"{name}.Server"), $"{name}.Server",
                new ServerBatteries(), version);

        var appProjects = wasmHosted
            ? new[]
            {
                $"{name}.Client/{name}.Client.csproj",
                $"{name}.Server/{name}.Server.csproj",
                $"{name}.Shared/{name}.Shared.csproj",
            }
            : [$"{name}.Server/{name}.Server.csproj"];

        var mobile = Materialize(
            System.IO.Path.Combine(targetDirectory, $"{name}.Mobile"), $"{name}.Mobile", mobileFiles);

        // One .gitignore / .editorconfig / .slnx for the whole solution, not one per half.
        var hygiene = Materialize(targetDirectory, name,
            ProjectHygiene([.. appProjects, $"{name}.Mobile/{name}.Mobile.csproj"]));

        List<ScaffoldFile> files = [.. app.Files.Where(IsNotHygiene), .. mobile, .. hygiene];

        return new ScaffoldResult(files, NativeNextSteps(name, host, ios, android))
        {
            Packages = ["Rask.Native", .. app.Packages],
            // No root csproj — restore (and the overwrite guard) target the solution, which pulls them all.
            RestoreTarget = $"{name}.slnx",
        };

        // The app generator emits its own solution-level files; this solution owns those.
        static bool IsNotHygiene(ScaffoldFile file) =>
            System.IO.Path.GetFileName(file.Path) is not (".gitignore" or ".editorconfig")
            && !file.Path.EndsWith(".slnx", StringComparison.Ordinal);
    }

    private static string NativeCsproj(string version, bool ios, bool android)
    {
        var targets = string.Join(';', NativeTargetFrameworks(ios, android));
        var platforms = ios && android ? "iOS + Android" : ios ? "iOS" : "Android";
        var workloads = string.Join(' ', NativeWorkloads(ios, android));
        var runCommands = string.Join('\n', NativeRunLines(ios, android).Select(line => "        " + line));

        // The per-platform blocks are assembled rather than interpolated inline: each is optional, and a
        // placeholder that is sometimes empty either leaves a blank line behind or has to carry its own,
        // which is how a generated file ends up with two blank lines in the middle of it.
        var sections = string.Concat(
            NativeIosProjectGroups(ios),
            NativeAndroidProjectGroups(android));

        var headGuards = NativeHeadGuards(ios, android);

        return $"""
        <Project Sdk="Microsoft.NET.Sdk">

          <!--
            A native {platforms} app that hosts a Rask app in-process inside a platform WebView (the WebView
            hybrid — C# runs natively, the view is a WebView). The shared component code (App.cs) compiles for
            every target below, and each platform head under Platforms/ provides the INativeWebView
            implementation for its WebView control.

            Requires the SDK workload(s):
                dotnet workload install {workloads}
            Run on a simulator/emulator:
        {runCommands}
          -->
          <PropertyGroup>
            <TargetFrameworks>{targets}</TargetFrameworks>
            <OutputType>Exe</OutputType>
            <Nullable>enable</Nullable>
            <ImplicitUsings>enable</ImplicitUsings>
            <RootNamespace>Company.RaskServer</RootNamespace>
            <ApplicationTitle>Rask App</ApplicationTitle>
            <ApplicationId>com.example.raskapp</ApplicationId>
            <ApplicationDisplayVersion>1.0</ApplicationDisplayVersion>
            <ApplicationVersion>1</ApplicationVersion>
          </PropertyGroup>

        {sections}  <ItemGroup>
            <PackageReference Include="Rask.Native" Version="{version}"/>
          </ItemGroup>
        {headGuards}
        </Project>

        """;
    }

    /// <summary>
    /// The iOS-only project configuration, omitted entirely when iOS is not a target. Each block ends with
    /// the blank line that separates it from what follows, so an omitted block leaves nothing behind.
    /// </summary>
    private static string NativeIosProjectGroups(bool ios) => ios
        ? """
          <PropertyGroup Condition="$(TargetFramework.Contains('-ios'))">
            <SupportedOSPlatformVersion>15.0</SupportedOSPlatformVersion>
          </PropertyGroup>

          <!-- Wire Platforms/iOS/Info.plist as THE app manifest (a None item whose Link filename is "Info.plist"
               is how .NET iOS finds it). Its UILaunchScreen makes the app render full-screen at the device's native
               resolution — without a launch screen iOS runs it letterboxed (black bars + everything scaled up). -->
          <ItemGroup Condition="$(TargetFramework.Contains('-ios'))">
            <None Remove="Platforms/iOS/Info.plist"/>
            <None Include="Platforms/iOS/Info.plist" Link="Info.plist"/>
          </ItemGroup>


        """
        : "";

    private static string NativeAndroidProjectGroups(bool android) => android
        ? """
          <PropertyGroup Condition="$(TargetFramework.Contains('-android'))">
            <SupportedOSPlatformVersion>24.0</SupportedOSPlatformVersion>
            <AndroidManifest>Platforms/Android/AndroidManifest.xml</AndroidManifest>
          </PropertyGroup>


        """
        : "";

    /// <summary>
    /// The per-TFM compile guards, emitted only for a multi-targeted project. With one target there is
    /// nothing to keep apart, and a guard naming a platform the project doesn't build reads as a promise
    /// that it could.
    /// </summary>
    private static string NativeHeadGuards(bool ios, bool android) => ios && android
        ? """

          <!-- Each platform head compiles only for its own TFM. -->
          <ItemGroup Condition="!$(TargetFramework.Contains('-ios'))">
            <Compile Remove="Platforms/iOS/**/*.cs"/>
          </ItemGroup>
          <ItemGroup Condition="!$(TargetFramework.Contains('-android'))">
            <Compile Remove="Platforms/Android/**/*.cs"/>
          </ItemGroup>

        """
        : "";

    /// <summary>The target frameworks for the selected platforms, iOS first (the order the SDK lists them).</summary>
    private static IEnumerable<string> NativeTargetFrameworks(bool ios, bool android)
    {
        if (ios)
        {
            yield return "net10.0-ios";
        }

        if (android)
        {
            yield return "net10.0-android";
        }
    }

    /// <summary>The SDK workloads the selected platforms need, for the `dotnet workload install` line.</summary>
    private static IEnumerable<string> NativeWorkloads(bool ios, bool android)
    {
        if (ios)
        {
            yield return "ios";
        }

        if (android)
        {
            yield return "android";
        }
    }

    /// <summary>The on-device run commands for the selected platforms.</summary>
    private static IEnumerable<string> NativeRunLines(bool ios, bool android)
    {
        if (android)
        {
            yield return $"{Commands.NativeRunCommands.Android}     # Android emulator";
        }

        if (ios)
        {
            yield return $"{Commands.NativeRunCommands.IOS}         # iOS simulator (macOS + Xcode)";
        }
    }

    private static string NativeInfoPlist(bool isLocal) =>
        isLocal ? NativeInfoPlistBody : NativeInfoPlistBody.Replace(
            "\t<key>UILaunchScreen</key>",
            // A remote head points at this solution's app half over http on the dev machine. ATS blocks that;
            // NSAllowsLocalNetworking is the narrow switch that permits it for localhost and .local without
            // opening the app to arbitrary cleartext. Drop it once the origin is https.
            "\t<key>NSAppTransportSecurity</key>\n"
            + "\t<dict>\n"
            + "\t\t<key>NSAllowsLocalNetworking</key>\n"
            + "\t\t<true/>\n"
            + "\t</dict>\n"
            + "\t<key>UILaunchScreen</key>",
            StringComparison.Ordinal);

