using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Rask.Jobs.Generators;

/// <summary>
/// Discovers every <c>Rask.Jobs.IJob</c> type in the compilation and emits a per-assembly
/// <c>[ModuleInitializer]</c> that registers each with <c>JobSerializerRegistry</c> (name → CLR type), so the
/// job processor rehydrates a stored job with no runtime <c>Type.GetType</c> / reflection.
/// </summary>
[Generator]
public sealed class JobRegistryGenerator : IIncrementalGenerator
{
    private const string MarkerInterface = "Rask.Jobs.IJob";

    /// <inheritdoc/>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var jobs = context.SyntaxProvider
            .CreateSyntaxProvider(
                static (node, _) => node is TypeDeclarationSyntax t && t.BaseList is { Types.Count: > 0 },
                static (ctx, _) => GetJobTypeName(ctx))
            .Where(static name => name is not null)
            .Select(static (name, _) => name!);

        context.RegisterSourceOutput(jobs.Collect(), static (spc, names) => Emit(spc, names));
    }

    // Returns the runtime full name (namespace.TypeName) of a type implementing IJob, else null.
    private static string? GetJobTypeName(GeneratorSyntaxContext ctx)
    {
        if (ctx.Node is not TypeDeclarationSyntax typeDecl ||
            ctx.SemanticModel.GetDeclaredSymbol(typeDecl) is not INamedTypeSymbol symbol)
        {
            return null;
        }

        if (symbol.IsAbstract || symbol.IsGenericType)
        {
            return null;
        }

        var implementsMarker = symbol.AllInterfaces.Any(static i =>
            i.ToDisplayString() == MarkerInterface);

        return implementsMarker ? symbol.ToDisplayString() : null;
    }

    private static void Emit(SourceProductionContext context, ImmutableArray<string> names)
    {
        var distinct = names.Distinct().OrderBy(static n => n, System.StringComparer.Ordinal).ToArray();
        if (distinct.Length == 0)
        {
            return;
        }

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("namespace Rask.Jobs.Generated");
        sb.AppendLine("{");
        sb.AppendLine("    internal static class __RaskJobsRegistry");
        sb.AppendLine("    {");
        sb.AppendLine("        [global::System.Runtime.CompilerServices.ModuleInitializer]");
        sb.AppendLine("        internal static void Init()");
        sb.AppendLine("        {");
        foreach (var name in distinct)
        {
            // The stored name is the runtime Type.FullName; register it against typeof(the type).
            sb.Append("            global::Rask.Jobs.JobSerializerRegistry.RegisterJob(\"")
              .Append(name)
              .Append("\", typeof(global::")
              .Append(name)
              .AppendLine("));");
        }

        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine("}");

        context.AddSource("__RaskJobsRegistry.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
    }
}
