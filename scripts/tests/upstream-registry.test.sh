#!/usr/bin/env bash
# gate-inputs: ^(src|tests)/
# scripts/upstream/followers.json against the tree: every follower's command and every file it says it writes
# exist, and every file that says a script under scripts/{upstream,flux,mdn} generated it belongs to a follower
# or to the "manual" list, with the reason it is still made by hand.
#
# That last check is what keeps the automation whole. A generator added without a follower is a pin nobody
# moves — it goes stale in silence, which is how the icons, the flags and the editor bundle got there. It reads
# only the first lines of each file (git grep), so it costs about a second on any change under src/ or tests/.
#
# Usage:  scripts/tests/upstream-registry.test.sh   (run by scripts/run-unit-local.sh)
set -euo pipefail

root="$(git rev-parse --show-toplevel)"
cd "$root"
registry=scripts/upstream/followers.json

failures=0
fail() { printf '  FAIL %s\n' "$1" >&2; failures=$((failures + 1)); }

echo "==> upstream registry"

jq -e . "$registry" >/dev/null || { echo "upstream registry: $registry is not JSON" >&2; exit 1; }

dupes="$(jq -r '[.followers[], .manual[]] | map(.name) | group_by(.) | map(select(length > 1) | .[0]) | .[]' "$registry")"
[ -z "$dupes" ] || fail "names used twice: $dupes"

bad_kind="$(jq -r '.followers[] | select(.kind != "regenerate" and .kind != "measure") | .name' "$registry")"
[ -z "$bad_kind" ] || fail "kind is neither regenerate nor measure: $bad_kind"

# The script a command runs: its first word, or its second after an interpreter.
while IFS=$'\t' read -r name script; do
  [ -e "$script" ] || fail "$name runs $script, which does not exist"
done < <(jq -r '.followers[] | [.name, (.run | split(" ") | if .[0] == "node" or .[0] == "python3" then .[1] else .[0] end)] | @tsv' "$registry")

while IFS=$'\t' read -r name generator; do
  [ -z "$generator" ] || [ -e "$generator" ] || fail "$name is generated by $generator, which does not exist"
done < <(jq -r '.manual[] | [.name, .generator] | @tsv' "$registry")

while IFS=$'\t' read -r name output; do
  [ -n "$(git ls-files -- "$output")" ] || fail "$name writes $output, which matches no file in the tree"
done < <(jq -r '(.followers[], .manual[]) | .name as $n | .outputs[] | [$n, .] | @tsv' "$registry")

[ -z "$(jq -r '.manual[] | select((.why // "") == "") | .name' "$registry")" ] || fail "a manual entry gives no reason"

# Every generator a file names in its header, against what the registry runs.
known="$(jq -r '.followers[].run, .manual[].generator' "$registry" | grep -oE 'scripts/[A-Za-z0-9_./-]+\.(mjs|py|sh)' | sort -u)"
while IFS=: read -r file line script; do
  [ "$line" -le 5 ] || continue
  printf '%s\n' "$known" | grep -qxF "$script" || fail "$file says $script generated it, and no follower or manual entry runs that"
done < <(git grep -nE -o '(Generated by|generated by|auto-generated>) ?scripts/(upstream|flux|mdn)/[A-Za-z0-9_-]+\.(mjs|py|sh)' -- src tests |
         sed -E 's/^([^:]+):([0-9]+):.*(scripts\/[A-Za-z0-9_./-]+)$/\1:\2:\3/')

if [ "$failures" -gt 0 ]; then
  echo "upstream registry: $failures check(s) failed" >&2
  exit 1
fi
echo "upstream registry: all checks passed"
