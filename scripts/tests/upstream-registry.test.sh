#!/usr/bin/env bash
# gate-inputs: ^(src|tests)/
# scripts/upstream/followers.json against the tree: every follower's command and every file it says it writes
# exist, and every file that says a script under scripts/{upstream,flux,mdn} generated it belongs to a follower
# or to the "manual" list, with the reason it is still made by hand.
#
# That last check is what keeps the automation whole. A generator added without a follower is a pin nobody
# moves — it goes stale in silence, which is how the icons, the flags and the editor bundle got there. It reads
# only the first lines of each file (git grep), so it costs about a second on any change under src/ or tests/.
#
# Usage:  scripts/tests/upstream-registry.test.sh   (run by scripts/run-unit-local.sh)
set -euo pipefail

root="$(git rev-parse --show-toplevel)"
cd "$root"
registry=scripts/upstream/followers.json

failures=0
fail() { printf '  FAIL %s\n' "$1" >&2; failures=$((failures + 1)); }

echo "==> upstream registry"

jq -e . "$registry" >/dev/null || { echo "upstream registry: $registry is not JSON" >&2; exit 1; }

dupes="$(jq -r '[.followers[], .manual[]] | map(.name) | group_by(.) | map(select(length > 1) | .[0]) | .[]' "$registry")"
[ -z "$dupes" ] || fail "names used twice: $dupes"

bad_kind="$(jq -r '.followers[] | select(.kind | IN("regenerate", "measure", "match") | not) | .name' "$registry")"
[ -z "$bad_kind" ] || fail "kind is not regenerate, measure or match: $bad_kind"

# A measure or match follower runs in a job of its own; one upstream.yml does not have is a follower nothing runs.
while read -r name; do
  grep -qE "^  $name:" .github/workflows/upstream.yml || fail "$name is a $(jq -r --arg n "$name" '.followers[] | select(.name == $n) | .kind' "$registry") follower, and upstream.yml has no '$name' job"
done < <(jq -r '.followers[] | select(.kind != "regenerate") | .name' "$registry")

bad_setup="$(jq -r '.followers[] | select((.setup // "dotnet") != "dotnet") | .name' "$registry")"
[ -z "$bad_setup" ] || fail "setup is neither absent nor dotnet (upstream-follow.yml knows no other): $bad_setup"

# Nothing in Rask runs on Node (scripts/tests/no-node.test.sh), the followers included.
on_node="$(jq -r '.followers[] | select(.run | test("^(node|npm|npx) ")) | .name' "$registry")"
[ -z "$on_node" ] || fail "runs on Node, which nothing in Rask may: $(echo $on_node)"

# The script or project a command runs: its first word, its second after python3, the project after
# `dotnet run --project`, or the third word after a bare `dotnet run`.
script='def script: split(" ") | if .[0] == "python3" then .[1] elif .[0:3] == ["dotnet", "run", "--project"] then .[3] elif .[0:2] == ["dotnet", "run"] then .[2] else .[0] end;'
while IFS=$'\t' read -r name path; do
  [ -e "$path" ] || fail "$name runs $path, which does not exist"
done < <(jq -r "$script"' .followers[] | select(.run | test("^(node|npm|npx) ") | not) | [.name, (.run | script)] | @tsv' "$registry")

while IFS=$'\t' read -r name path; do
  [ -z "$path" ] || [ -e "$path" ] || fail "$name is generated by $path, which does not exist"
done < <(jq -r "$script"' .manual[] | [.name, (.generator | script)] | @tsv' "$registry")

# A Flux harness command a follower or manual entry runs, as a generated header names it.
flux_commands="$(jq -r '.followers[].run, .manual[].generator' "$registry" | sed -nE 's#^dotnet run --project scripts/flux/Flux .*-- ([a-z-]+).*$#scripts/flux/Flux (flux \1)#p' | sort -u)"
while IFS=: read -r file line command; do
  [ "$line" -le 5 ] || continue
  printf '%s\n' "$flux_commands" | grep -qxF "$command" || fail "$file says $command generated it, and no follower or manual entry runs that"
done < <(git grep -nE -o '(Generated by|generated by|auto-generated>) ?scripts/flux/Flux \(flux [a-z-]+\)' -- src tests |
         sed -E 's/^([^:]+):([0-9]+):.*(scripts\/flux\/Flux \(flux [a-z-]+\))$/\1:\2:\3/')

while IFS=$'\t' read -r name output; do
  [ -n "$(git ls-files -- "$output")" ] || fail "$name writes $output, which matches no file in the tree"
done < <(jq -r '(.followers[], .manual[]) | .name as $n | .outputs[] | [$n, .] | @tsv' "$registry")

[ -z "$(jq -r '.manual[] | select((.why // "") == "") | .name' "$registry")" ] || fail "a manual entry gives no reason"

# Every generator a file names in its header, against what the registry runs.
known="$(jq -r '.followers[].run, .manual[].generator' "$registry" | grep -oE 'scripts/[A-Za-z0-9_./-]+\.(mjs|py|sh|cs)' | sort -u)"
while IFS=: read -r file line script; do
  [ "$line" -le 5 ] || continue
  printf '%s\n' "$known" | grep -qxF "$script" || fail "$file says $script generated it, and no follower or manual entry runs that"
done < <(git grep -nE -o '(Generated by|generated by|auto-generated>) ?scripts/(upstream|flux|mdn)/[A-Za-z0-9_-]+\.(mjs|py|sh|cs)' -- src tests |
         sed -E 's/^([^:]+):([0-9]+):.*(scripts\/[A-Za-z0-9_./-]+)$/\1:\2:\3/')

if [ "$failures" -gt 0 ]; then
  echo "upstream registry: $failures check(s) failed" >&2
  exit 1
fi
echo "upstream registry: all checks passed"
