#!/usr/bin/env python3
"""Follows Unicode CLDR for what Ui.DatetimePicker's button writes between a moment's date and its time.

Flux's button writes what the browser's Intl writes in the picker's `locale`. Measured on its live page
(2026-10-26): where CLDR joins a long date and a time with ONE word (en "at", fr "à", de "um"), the button writes
the date, that word in grey and the time; elsewhere (ja, hu, es "a las", ru "г. в", sv "kl.") it writes the moment
as one text, joined by CLDR's at-time glue for a medium date ("{1}, {0}", ja "{1} {0}", bg "{1}, {0} ч."). The word
is what Intl sees between the two: the long date's trailing literal, the at-time glue's own, the short time's
leading one. Checked against Flux's page in 43 locales, every join equal.

The data is cldr-dates-full's latest release on npm (the Unicode CLDR JSON, Unicode License v3), read in memory and
checked against the registry's integrity. Out of it come:

    src/Rask.Ui/UiDatetimePickerJoins.g.cs    locale -> " word " or "{1}, {0}": only where it differs from its
                                               parent (fr-CA -> fr -> root), and the release it was taken from
    src/Rask.Ui/Resources/cldr.LICENSE.txt     that release's licence, packed with the kit

Usage:  scripts/upstream/cldr.py            # regenerate from the latest release
        scripts/upstream/cldr.py --check    # exit 1 when the committed files are not that release's

scripts/upstream/follow.sh runs it every day.
"""
import json
import re
import sys
import unicodedata

import npm
from upstream import ROOT, ShapeChanged, follow

PACKAGE = "cldr-dates-full"
ROOT_LOCALE = "und"
GENERATOR = "scripts/upstream/cldr.py"
JOINS = ROOT / "src/Rask.Ui/UiDatetimePickerJoins.g.cs"
LICENCE = ROOT / "src/Rask.Ui/Resources/cldr.LICENSE.txt"
GREGORIAN = re.compile(r"package/main/([^/]+)/ca-gregorian\.json")


def tokens(pattern):
    """An LDML pattern as fields ("{0}", "MMMM") and the literal text between them, quotes resolved."""
    out = []

    def text(value):
        if out and "field" not in out[-1]:
            out[-1]["text"] += value
        else:
            out.append({"text": value})

    at = 0
    while at < len(pattern):
        c = pattern[at]
        if c == "'":
            end = pattern.find("'", at + 1)
            if end < 0:
                raise ShapeChanged(f"unterminated quote in {pattern}")
            text("'" if end == at + 1 else pattern[at + 1:end])
            at = end + 1
        elif c == "{":
            end = pattern.find("}", at)
            out.append({"field": pattern[at:end + 1]})
            at = end + 1
        elif re.match(r"[A-Za-z]", c):
            end = at
            while end < len(pattern) and pattern[end] == c:
                end += 1
            out.append({"field": pattern[at:end]})
            at = end
        else:
            text(c)
            at += 1
    return out


def trailing(parts):
    return "" if not parts or "field" in parts[-1] else parts[-1]["text"]


def leading(parts):
    return "" if not parts or "field" in parts[0] else parts[0]["text"]


def join_of(gregorian):
    """What the button writes between the date and the time: " word " when Intl puts one word there, else the medium
    at-time glue."""
    at_time = gregorian["dateTimeFormats-atTime"]["standard"]
    glue = tokens(at_time["long"])
    date, time = gregorian["dateFormats"]["long"], gregorian["timeFormats"]["short"]
    date_at = next((i for i, t in enumerate(glue) if t.get("field") == "{1}"), -1)
    time_at = next((i for i, t in enumerate(glue) if t.get("field") == "{0}"), -1)
    if date_at >= 0 and time_at == date_at + 2 and "field" not in glue[date_at + 1]:
        word = trailing(tokens(date)) + glue[date_at + 1]["text"] + leading(tokens(time))
        if len(word) > 2 and word[0] == " " and word[-1] == " " and word[1:-1].isalpha():
            return word
    return "".join(t.get("field", t.get("text")) for t in tokens(at_time["medium"]))


def literal(value):
    """A C# string literal: letters as they are; what cannot be seen (a no-break space, a direction mark) as an escape."""
    def escape(c):
        code = ord(c) if ord(c) <= 0xFFFF else 0xD800 + ((ord(c) - 0x10000) >> 10)
        return f"\\u{code:04x}"
    return "".join(escape(c) if c != " " and unicodedata.category(c)[0] in "CZ" else c
                   for c in json.dumps(value, ensure_ascii=False))


def source(version, joins, own):
    rows = "\n".join(f"        [{literal(locale)}] = {literal(value)}," for locale, value in own)
    return f"""// <auto-generated>
// Generated by {GENERATOR} from Unicode CLDR {version} ({PACKAGE}, Unicode License v3: Resources/cldr.LICENSE.txt).
// Do not edit: change the script and run it.
// </auto-generated>

#nullable enable

namespace Rask;

internal static partial class UiDatetimePickerJoins
{{
    /// <summary>The CLDR release the joins come from.</summary>
    internal const string CldrVersion = {literal(version)};

    /// <summary>What CLDR's root locale joins with.</summary>
    private const string Root = {literal(joins[ROOT_LOCALE])};

    // " word " where the button writes the date, the word and the time; else the pattern the moment is written in
    // as one text, {{1}} the date and {{0}} the time. Only where a locale differs from its parent.
    private static readonly Dictionary<string, string> Own = new(StringComparer.OrdinalIgnoreCase)
    {{
{rows}
    }};
}}
"""


def step(check):
    release = npm.release(PACKAGE)
    files = npm.files(npm.tarball(release), lambda p: p == "package/LICENSE" or GREGORIAN.fullmatch(p) is not None)

    joins = {}
    for path, data in files.items():
        locale = GREGORIAN.fullmatch(path)
        if locale:
            main = json.loads(data.decode("utf-8"))["main"]
            joins[locale.group(1)] = join_of(next(iter(main.values()))["dates"]["calendars"]["gregorian"])

    if len(joins) < 500 or ROOT_LOCALE not in joins:
        raise ShapeChanged(f"only {len(joins)} locales in {PACKAGE} {release['version']}")
    for locale, expected in [("en", " at "), ("fr", " à "), ("ja", "{1} {0}")]:
        if joins.get(locale) != expected:
            raise ShapeChanged(f"{locale} joins with {json.dumps(joins.get(locale))}, not {json.dumps(expected)}: CLDR's shape moved")

    # A locale is written only where it differs from what its parent resolves to.
    def parent(locale):
        return locale[:locale.rfind("-")] if "-" in locale else ROOT_LOCALE

    def resolved(locale):
        while locale not in joins:
            locale = parent(locale)
        return joins[locale]

    own = sorted((locale, value) for locale, value in joins.items() if locale != ROOT_LOCALE and value != resolved(parent(locale)))

    if "package/LICENSE" not in files:
        raise ShapeChanged("no LICENSE in the tarball")
    licence = (f"Unicode CLDR {release['version']} ({PACKAGE} on npm) — https://cldr.unicode.org\n"
               f"UiDatetimePickerJoins.g.cs is derived from its date-time patterns. Generated by {GENERATOR}.\n\n"
               + files["package/LICENSE"].decode("utf-8"))
    outputs = {JOINS: source(release["version"], joins, own), LICENCE: licence}

    if check:
        stale = sum(1 for path, text in outputs.items() if not path.exists() or path.read_text(encoding="utf-8") != text)
        if stale:
            raise ShapeChanged(f"{stale} generated file(s) are stale — run: {GENERATOR}")
    else:
        for path, text in outputs.items():
            path.write_text(text, encoding="utf-8")
    return f"{PACKAGE} {release['version']} — {len(joins)} locales, {len(own)} written"


if __name__ == "__main__":
    sys.exit(follow("cldr", lambda: step("--check" in sys.argv[1:])))
