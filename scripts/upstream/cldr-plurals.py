#!/usr/bin/env python3
"""Follows Unicode CLDR's plural rules — the data the curated table in src/Rask.Generators/Translations/PluralRules.cs
is transcribed from.

The table stays written by hand (it carries only what an integer count can select, and a language it does not carry
is a build error). What follows CLDR is this snapshot of every language's cardinal rules, taken from cldr-core's
latest release on npm (checked against the registry's integrity), with the samples dropped:

    tests/Rask.Generators.Tests/cldr-plurals.json

PluralRulesMatchCldrTests evaluates both for every whole count up to 10,000. So a release that changes a carried
language's rule fails the gates on the follower's commit, which opens its issue: a person decides what the table says.

Usage:  scripts/upstream/cldr-plurals.py            # take the latest release
        scripts/upstream/cldr-plurals.py --check    # exit 1 when the snapshot is not that release's

scripts/upstream/follow.sh runs it every day.
"""
import json
import re
import sys

import npm
from upstream import ROOT, ShapeChanged, follow

PACKAGE = "cldr-core"
PLURALS = "package/supplemental/plurals.json"
GENERATOR = "scripts/upstream/cldr-plurals.py"
OUTPUT = ROOT / "tests/Rask.Generators.Tests/cldr-plurals.json"


def step(check):
    manifest = npm.release(PACKAGE)
    files = npm.files(npm.tarball(manifest), lambda p: p == PLURALS)
    if PLURALS not in files:
        raise ShapeChanged(f"no {PLURALS} in {PACKAGE} {manifest['version']}")
    cardinal = json.loads(files[PLURALS].decode("utf-8"))["supplemental"].get("plurals-type-cardinal")
    if not cardinal:
        raise ShapeChanged("no plurals-type-cardinal: CLDR's shape moved")

    languages = sorted(cardinal)
    if len(languages) < 150 or "en" not in cardinal or "ar" not in cardinal:
        raise ShapeChanged(f"only {len(languages)} languages: CLDR's shape moved")

    rules = {language: {key.replace("pluralRule-count-", "", 1): re.sub(r"\s*@.*$", "", rule, flags=re.S).strip()
                        for key, rule in cardinal[language].items()} for language in languages}
    text = json.dumps({
        "_": f"Generated by {GENERATOR} from {PACKAGE} {manifest['version']} (Unicode License v3).",
        "release": manifest["version"],
        "integrity": manifest["dist"]["integrity"],
        "cardinal": rules,
    }, indent=1, ensure_ascii=False) + "\n"

    if check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text:
            raise ShapeChanged(f"the snapshot is stale — run: {GENERATOR}")
    else:
        OUTPUT.write_text(text, encoding="utf-8")
    return f"{PACKAGE} {manifest['version']} — {len(languages)} languages"


if __name__ == "__main__":
    sys.exit(follow("cldr plurals", lambda: step("--check" in sys.argv[1:])))
