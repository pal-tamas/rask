#!/usr/bin/env bash
# Bring everything Rask is generated from to its upstream's latest stable release, in the working tree.
#
# The followers, what each runs and the files it writes are scripts/upstream/followers.json — the one list
# upstream.yml makes a job of, and scripts/tests/upstream-registry.test.sh holds the tree to. A follower of
# kind "regenerate" runs here; "measure" (Flux UI, which needs a browser and whose lock is measured on the CI
# runner) and "match" (Rask.Ui's pages held to Flux's, which writes nothing) run in upstream.yml's job of that name. "manual" names what is still generated by hand, and why.
#
# Dependabot keeps what it can read (.github/dependabot.yml): NuGet, the npm lockfiles, base images, actions.
# It commits nothing: `git status` afterwards is the report. .github/workflows/upstream.yml runs this
# every day, ONE follower per job, and gates and lands each one's commit on its own — a release that
# breaks a gate holds back that source only. Run it by hand to see what tomorrow's run would do.
#
# Usage:  scripts/upstream/follow.sh              # every follower, in this tree
#         scripts/upstream/follow.sh mdn cldr     # these only
#         scripts/upstream/follow.sh --list       # the names upstream.yml makes a job of
#
# Serial: every step writes the one tree, and MDN records the surface from a build of the new snapshot.
set -euo pipefail

root="$(cd "$(dirname "$0")/../.." && pwd)"
cd "$root"
registry=scripts/upstream/followers.json

names() { jq -r '.followers[] | select(.kind == "regenerate") | .name' "$registry"; }

follow() {
  local run
  run="$(jq -r --arg n "$1" '.followers[] | select(.kind == "regenerate" and .name == $n) | .run' "$registry")"
  if [ -z "$run" ]; then
    echo "follow.sh: no follower '$1' (follow.sh --list names them)" >&2
    exit 2
  fi
  # A command line from the registry, which is committed and reviewed like this script: word-split, never eval'd.
  read -r -a command <<<"$run"
  "${command[@]}"
}

if [ "${1:-}" = "--list" ]; then
  names
  exit 0
fi

if [ $# -eq 0 ]; then
  set -- $(names)
fi
for name in "$@"; do
  follow "$name"
done
