#!/usr/bin/env node
// Follows Unicode CLDR's plural rules — the data the curated table in src/Rask.Generators/Translations/PluralRules.cs
// is transcribed from.
//
// The table stays written by hand (it carries only what an integer count can select, and a language it does not
// carry is a build error). What follows CLDR is this snapshot of every language's cardinal rules, taken from
// cldr-core's latest release on npm (checked against the registry's integrity), with the samples dropped:
//
//   tests/Rask.Generators.Tests/cldr-plurals.json
//
// PluralRulesMatchCldrTests evaluates both for every whole count up to 10,000. So a release that changes a
// carried language's rule fails the gates on the follower's commit, which opens its issue: a person decides
// what the table says.
//
// Usage:  node scripts/upstream/cldr-plurals.mjs            # take the latest release
//         node scripts/upstream/cldr-plurals.mjs --check    # exit 1 when the snapshot is not that release's
//
// scripts/upstream/follow.sh runs it every day.

import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { latest } from './npm.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const PACKAGE = 'cldr-core';
const PLURALS = 'package/supplemental/plurals.json';
const output = join(root, 'tests', 'Rask.Generators.Tests', 'cldr-plurals.json');

const release = await latest(PACKAGE, path => path === PLURALS);
const cardinal = JSON.parse(release.files.get(PLURALS) ?? fail(`no ${PLURALS} in ${PACKAGE} ${release.version}`))
  .supplemental['plurals-type-cardinal'] ?? fail('no plurals-type-cardinal: CLDR\'s shape moved');

const languages = Object.keys(cardinal).sort();
if (languages.length < 150 || !cardinal.en || !cardinal.ar) fail(`only ${languages.length} languages: CLDR's shape moved`);

const rules = {};
for (const language of languages) {
  rules[language] = {};
  for (const [key, rule] of Object.entries(cardinal[language])) {
    rules[language][key.replace('pluralRule-count-', '')] = rule.replace(/\s*@.*$/s, '').trim();
  }
}

const text = JSON.stringify({
  _: `Generated by scripts/upstream/cldr-plurals.mjs from ${PACKAGE} ${release.version} (Unicode License v3).`,
  release: release.version,
  integrity: release.integrity,
  cardinal: rules,
}, null, 1) + '\n';

if (process.argv.includes('--check')) {
  if ((await readFile(output, 'utf8').catch(() => '')) !== text) fail('the snapshot is stale — run: node scripts/upstream/cldr-plurals.mjs');
} else {
  await writeFile(output, text);
}

console.log(`cldr plurals: ${PACKAGE} ${release.version} — ${languages.length} languages.`);

function fail(message) {
  console.error(`cldr plurals: ${message}`);
  process.exit(1);
}
