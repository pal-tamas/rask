#!/usr/bin/env node
// Follows Unicode CLDR for what Ui.DatetimePicker's button writes between a moment's date and its time.
//
// Flux's button writes what the browser's Intl writes in the picker's `locale`. Measured on its live page
// (2026-10-26): where CLDR joins a long date and a time with ONE word (en "at", fr "à", de "um"), the button
// writes the date, that word in grey and the time; elsewhere (ja, hu, es "a las", ru "г. в", sv "kl.") it
// writes the moment as one text, joined by CLDR's at-time glue for a medium date ("{1}, {0}", ja "{1} {0}",
// bg "{1}, {0} ч."). The word is what Intl sees between the two: the long date's trailing literal, the at-time
// glue's own, the short time's leading one. Checked against Flux's page in 43 locales, every join equal.
//
// The data is cldr-dates-full's latest release on npm (the Unicode CLDR JSON, Unicode License v3), read in
// memory and checked against the registry's integrity. Out of it come:
//
//   src/Rask.Ui/UiDatetimePickerJoins.g.cs    locale -> " word " or "{1}, {0}": only where it differs from its
//                                              parent (fr-CA -> fr -> root), and the release it was taken from
//   src/Rask.Ui/Resources/cldr.LICENSE.txt     that release's licence, packed with the kit
//
// Usage:  node scripts/upstream/cldr.mjs            # regenerate from the latest release
//         node scripts/upstream/cldr.mjs --check    # exit 1 when the committed files are not that release's
//
// scripts/upstream/follow.sh runs it every day.

import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gunzipSync } from 'node:zlib';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const PACKAGE = 'cldr-dates-full';
const ROOT_LOCALE = 'und';

const release = await json(`https://registry.npmjs.org/${PACKAGE}/latest`);
const files = untar(gunzipSync(await download(release.dist.tarball, release.dist.integrity)),
  path => path === 'package/LICENSE' || /^package\/main\/[^/]+\/ca-gregorian\.json$/.test(path));

const joins = new Map();
for (const [path, text] of files) {
  const locale = /^package\/main\/([^/]+)\//.exec(path)?.[1];
  if (!locale) continue;
  const gregorian = Object.values(JSON.parse(text).main)[0].dates.calendars.gregorian;
  joins.set(locale, join_(gregorian));
}

if (joins.size < 500 || !joins.has(ROOT_LOCALE)) fail(`only ${joins.size} locales in ${PACKAGE} ${release.version}`);
for (const [locale, expected] of [['en', ' at '], ['fr', ' à '], ['ja', '{1} {0}']]) {
  if (joins.get(locale) !== expected) fail(`${locale} joins with ${JSON.stringify(joins.get(locale))}, not ${JSON.stringify(expected)}: CLDR's shape moved`);
}

// A locale is written only where it differs from what its parent resolves to.
const parent = locale => locale.includes('-') ? locale.slice(0, locale.lastIndexOf('-')) : ROOT_LOCALE;
const resolved = locale => joins.get(locale) ?? (locale === ROOT_LOCALE ? fail('no root') : resolved(parent(locale)));
const own = [...joins].filter(([locale, value]) => locale !== ROOT_LOCALE && value !== resolved(parent(locale)))
  .sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0);

const licence = files.get('package/LICENSE') ?? fail('no LICENSE in the tarball');
const outputs = new Map([
  [join(root, 'src', 'Rask.Ui', 'UiDatetimePickerJoins.g.cs'), source()],
  [join(root, 'src', 'Rask.Ui', 'Resources', 'cldr.LICENSE.txt'), `Unicode CLDR ${release.version} (${PACKAGE} on npm) — https://cldr.unicode.org\n`
    + 'UiDatetimePickerJoins.g.cs is derived from its date-time patterns. Generated by scripts/upstream/cldr.mjs.\n\n' + licence],
]);

const check = process.argv.includes('--check');
let stale = 0;
for (const [path, text] of outputs) {
  if (check) stale += (await readFile(path, 'utf8').catch(() => '')) === text ? 0 : 1;
  else await writeFile(path, text);
}

if (check && stale) fail(`${stale} generated file(s) are stale — run: node scripts/upstream/cldr.mjs`);
console.log(`cldr: ${PACKAGE} ${release.version} — ${joins.size} locales, ${own.length} written.`);

// What the button writes between the date and the time: " word " when Intl puts one word there, else the medium at-time glue.
function join_(gregorian) {
  const glue = tokens(gregorian['dateTimeFormats-atTime'].standard.long);
  const date = gregorian.dateFormats.long, time = gregorian.timeFormats.short;
  const dateAt = glue.findIndex(t => t.field === '{1}'), timeAt = glue.findIndex(t => t.field === '{0}');
  if (dateAt >= 0 && timeAt === dateAt + 2 && !glue[dateAt + 1].field) {
    const word = trailing(tokens(date)) + glue[dateAt + 1].text + leading(tokens(time));
    if (/^ \p{L}+ $/u.test(word)) return word;
  }

  return tokens(gregorian['dateTimeFormats-atTime'].standard.medium).map(t => t.field ?? t.text).join('');
}

// An LDML pattern as fields ("{0}", "MMMM") and the literal text between them, quotes resolved.
function tokens(pattern) {
  const out = [];
  const text = value => out.at(-1) && !out.at(-1).field ? out.at(-1).text += value : out.push({ text: value });
  for (let at = 0; at < pattern.length;) {
    const c = pattern[at];
    if (c === "'") {
      const end = pattern.indexOf("'", at + 1);
      if (end < 0) fail(`unterminated quote in ${pattern}`);
      text(end === at + 1 ? "'" : pattern.slice(at + 1, end));
      at = end + 1;
    } else if (c === '{') {
      const end = pattern.indexOf('}', at);
      out.push({ field: pattern.slice(at, end + 1) });
      at = end + 1;
    } else if (/[A-Za-z]/.test(c)) {
      let end = at;
      while (pattern[end] === c) end++;
      out.push({ field: pattern.slice(at, end) });
      at = end;
    } else {
      text(c);
      at++;
    }
  }

  return out;
}

function trailing(list) { return list.at(-1)?.field ? '' : list.at(-1)?.text ?? ''; }

function leading(list) { return list[0]?.field ? '' : list[0]?.text ?? ''; }

function source() {
  // Letters as they are; what cannot be seen (a no-break space, a direction mark) as an escape.
  const literal = value => JSON.stringify(value).replace(/(?! )[\p{C}\p{Z}]/gu, c => `\\u${c.charCodeAt(0).toString(16).padStart(4, '0')}`);
  const rows = own.map(([locale, value]) => `        [${literal(locale)}] = ${literal(value)},`).join('\n');
  return `// <auto-generated>
// Generated by scripts/upstream/cldr.mjs from Unicode CLDR ${release.version} (${PACKAGE}, Unicode License v3: Resources/cldr.LICENSE.txt).
// Do not edit: change the script and run it.
// </auto-generated>

#nullable enable

namespace Rask;

internal static partial class UiDatetimePickerJoins
{
    /// <summary>The CLDR release the joins come from.</summary>
    internal const string CldrVersion = ${literal(release.version)};

    /// <summary>What CLDR's root locale joins with.</summary>
    private const string Root = ${literal(joins.get(ROOT_LOCALE))};

    // " word " where the button writes the date, the word and the time; else the pattern the moment is written in
    // as one text, {1} the date and {0} the time. Only where a locale differs from its parent.
    private static readonly Dictionary<string, string> Own = new(StringComparer.OrdinalIgnoreCase)
    {
${rows}
    };
}
`;
}

async function json(url) {
  const response = await fetch(url);
  if (!response.ok) fail(`${url}: HTTP ${response.status}`);
  return response.json();
}

async function download(url, integrity) {
  const response = await fetch(url);
  if (!response.ok) fail(`${url}: HTTP ${response.status}`);
  const bytes = Buffer.from(await response.arrayBuffer());
  const digest = `sha512-${createHash('sha512').update(bytes).digest('base64')}`;
  if (digest !== integrity) fail(`${url} is not the tarball the registry names (${digest})`);
  return bytes;
}

// A ustar archive, read in place: 512-byte headers, each followed by its file rounded up to 512. Only the
// files `wanted` names are decoded.
function untar(archive, wanted) {
  const entries = new Map();
  const field = (at, start, length) => archive.subarray(at + start, at + start + length).toString('utf8').replace(/\0.*$/s, '');
  for (let at = 0; at + 512 <= archive.length;) {
    const name = field(at, 0, 100);
    if (!name) break;
    const size = parseInt(field(at, 124, 12).trim() || '0', 8);
    const prefix = field(at, 345, 155);
    const path = prefix ? `${prefix}/${name}` : name;
    if ((field(at, 156, 1) === '0' || field(at, 156, 1) === '') && wanted(path)) {
      entries.set(path, archive.subarray(at + 512, at + 512 + size).toString('utf8'));
    }

    at += 512 + Math.ceil(size / 512) * 512;
  }

  return entries;
}

function fail(message) {
  console.error(`cldr: ${message}`);
  process.exit(1);
}
