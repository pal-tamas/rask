using System.Text;
using System.Text.RegularExpressions;

namespace Rask.Flux.Commands;

/// <summary>
///     Vendors the flag artwork Ui.Flag draws: country-flag-icons' 3:2 set.
/// </summary>
/// <remarks>
///     country-flag-icons (https://gitlab.com/catamphetamine/country-flag-icons) is MIT-licensed, Copyright (c) 2020
///     @catamphetamine. It is the set Flux UI's <c>flux:flag</c> serves: 250 of the files on fluxui.dev are byte-for-byte
///     the project's sources and 4 its minified ones. The npm tarball — the same drawings, minified by the project itself
///     — is npm's latest release, checked against the registry's integrity, read in memory, and never unpacked to disk.
///     Out of its <c>3x2</c> folder come src/Rask.Ui/Flags/&lt;CC&gt;.svg (one file per region code, served as a static
///     file, never embedded), src/Rask.Ui/Flags/LICENSE.txt (the project's licence, with the release) and
///     src/Rask.Ui/UiFlagRegistry.g.cs (which codes there are, and the release the URLs carry).
///     <para>
///         NOT here: UN and CQ (Sark). Unicode's RGI list has them and Flux serves them, but from artwork that is not this
///         project's and whose licence could not be established. Ui.Flag draws its empty frame for them.
///     </para>
///     <code>
///     flux flags            # regenerate from the latest release
///     flux flags --check    # exit 1 when the committed files are not that release's
///     </code>
///     The upstream follower runs it every day.
/// </remarks>
[FluxCommand("flags", "Ui.Flag's artwork from npm's latest country-flag-icons")]
public sealed partial class Flags : IFluxCommand
{
    private const string Label = "flux flags";
    private const string Generator = "scripts/flux/Flux (flux flags)";

    // Private-use codes the project draws and Flux's registry does not answer for.
    private static readonly string[] NotFlux = ["XA", "XC", "XO"];

    // Unicode gives these three the flag of the country they belong to. One file each, not two.
    private static readonly (string Alias, string Target)[] Aliases = [("CP", "FR"), ("DG", "IO"), ("EA", "ES")];

    /// <inheritdoc />
    public async Task<int> Run(string[] args)
    {
        var release = await Npm.Latest("country-flag-icons", Label);
        var files = Npm.Untar(await Npm.Tarball(release, Label));
        var flags = new SortedDictionary<string, string>(StringComparer.Ordinal);
        var order = new List<string>();
        foreach (var (path, svg) in files)
        {
            var code = FlagPath().Match(path);
            if (!code.Success || NotFlux.Contains(code.Groups[1].Value))
            {
                continue;
            }

            // Served to an <img>, where nothing in an SVG runs — and still held to plain artwork.
            if (!PlainSvg().IsMatch(svg) || Active().IsMatch(svg))
            {
                throw Npm.Fail(Label, $"{path}: not plain artwork");
            }

            flags[code.Groups[1].Value] = svg;
            order.Add(code.Groups[1].Value);
        }

        if (flags.Count < 250)
        {
            throw Npm.Fail(Label, $"only {flags.Count} flags in the tarball");
        }

        foreach (var (alias, target) in Aliases)
        {
            if (flags.ContainsKey(alias) || !flags.ContainsKey(target))
            {
                throw Npm.Fail(Label, $"alias {alias} -> {target} no longer holds");
            }
        }

        var licence = files.TryGetValue("package/LICENSE", out var text) ? text : throw Npm.Fail(Label, "no LICENSE in the tarball");
        var folder = Repo.Path("src", "Rask.Ui", "Flags");
        var outputs = new Dictionary<string, string>(StringComparer.Ordinal)
        {
            [Path.Combine(folder, "LICENSE.txt")] = $"country-flag-icons {release.Version} — https://gitlab.com/catamphetamine/country-flag-icons\n"
                + $"The .svg files in this folder are that project's 3x2 flags, unmodified. Generated by {Generator}.\n\n{licence}",
            [Repo.Path("src", "Rask.Ui", "UiFlagRegistry.g.cs")] = RegistrySource(release, flags.Keys),
        };
        foreach (var code in order)
        {
            outputs[Path.Combine(folder, $"{code}.svg")] = flags[code];
        }

        var check = args.Contains("--check");
        var present = Directory.Exists(folder) ? Directory.GetFiles(folder) : [];
        var strays = present.Where(path => !outputs.ContainsKey(path)).ToList();
        var stale = strays.Count;
        if (!check)
        {
            Directory.CreateDirectory(folder);
            strays.ForEach(File.Delete);
        }

        foreach (var (path, content) in outputs)
        {
            if (check)
            {
                stale += (File.Exists(path) ? await File.ReadAllTextAsync(path) : "") == content ? 0 : 1;
            }
            else
            {
                await File.WriteAllTextAsync(path, content);
            }
        }

        if (check && stale > 0)
        {
            throw Npm.Fail(Label, $"{stale} generated file(s) are stale — run: dotnet run --project scripts/flux/Flux -- flags");
        }

        Console.WriteLine($"flux flags: country-flag-icons {release.Version} — {flags.Count} flags, {flags.Values.Sum(svg => Encoding.UTF8.GetByteCount(svg))} bytes of SVG.");
        return 0;
    }

    private static string RegistrySource(Npm.Release release, IEnumerable<string> codes)
    {
        var aliases = string.Join('\n', Aliases.Select(a => $"            \"{a.Alias}\" => \"{a.Target}\","));
        return $$"""
            // <auto-generated>
            // Generated by {{Generator}} from country-flag-icons {{release.Version}} (MIT, Copyright (c) 2020 @catamphetamine),
            // {{release.Tarball}}, {{release.Integrity}}.
            // Do not edit: change the script and run it.
            // </auto-generated>

            #nullable enable

            namespace Rask;

            /// <summary>Which region codes <see cref="UiFlag" /> has a drawing for: the files in <c>Flags/</c>.</summary>
            internal static class UiFlagRegistry
            {
                /// <summary>The release the drawings come from. It rides on every flag URL, so a new set is fetched anew.</summary>
                internal const string Version = "{{release.Version}}";

                // Every code, two letters each, in order.
                private const string Codes =
                    "{{string.Concat(codes)}}";

                /// <summary>The file that draws <paramref name="country" />, or <see langword="null" /> when there is none.</summary>
                internal static string? File(string country)
                {
                    if (country.Length != 2 || !char.IsAsciiLetter(country[0]) || !char.IsAsciiLetter(country[1]))
                    {
                        return null;
                    }

                    var code = country.ToUpperInvariant() switch
                    {
            {{aliases}}
                        var upper => upper,
                    };

                    for (var at = 0; at < Codes.Length; at += 2)
                    {
                        if (Codes[at] == code[0] && Codes[at + 1] == code[1])
                        {
                            return code;
                        }
                    }

                    return null;
                }
            }

            """.Replace("\r\n", "\n", StringComparison.Ordinal);
    }

    [GeneratedRegex("^package/3x2/([A-Z]{2})\\.svg$")]
    private static partial Regex FlagPath();

    [GeneratedRegex(@"^<svg [^>]*viewBox=""[0-9. ]+""[^>]*>.*</svg>\s*$", RegexOptions.Singleline)]
    private static partial Regex PlainSvg();

    [GeneratedRegex(@"<script|<foreignObject|\son\w+=|href=""(?!#)", RegexOptions.IgnoreCase)]
    private static partial Regex Active();
}
