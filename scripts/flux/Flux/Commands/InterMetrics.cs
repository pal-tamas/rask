using System.Globalization;
using System.Text;
using System.Text.Json.Nodes;
using Microsoft.Playwright;

namespace Rask.Flux.Commands;

/// <summary>
///     Writes src/Rask.Ui/UiChartInter.Metrics.cs: Inter's advance widths and kerning pairs, in font units.
/// </summary>
/// <remarks>
///     Flux sizes a chart's gutters by measuring its tick labels in the browser. Ui.Chart is drawn in C#, where there is
///     no browser to ask, so it carries the numbers the browser would answer with: every glyph's advance and every
///     kerning pair of the face Flux's docs (and a Tailwind app's default <c>font-sans</c> stack with Inter loaded) are
///     set in. Measured at 2048px, where a font unit is a pixel, on a page that has Inter loaded; a label's width at 12px
///     is then ceil(units * 12 / 2048 * 64) / 64, which is what Chromium reports.
///     <code>flux inter-metrics        (rarely: when Inter itself changes)</code>
/// </remarks>
[FluxCommand("inter-metrics", "Inter's advances and kerning for Ui.Chart (UiChartInter.Metrics.cs)")]
public sealed class InterMetrics : IFluxCommand
{
    private static readonly int[] Weights = [400, 500];

    /// <inheritdoc />
    public async Task<int> Run(string[] args)
    {
        var chars = Enumerable.Range(0, 95).Select(i => ((char)(32 + i)).ToString()).Concat("€£¥°…–—’·×".Select(c => c.ToString())).ToList();
        var browser = await Browsers.Chromium();
        var page = await browser.NewPageAsync();
        await page.GotoAsync("https://fluxui.dev/components/chart", new PageGotoOptions { WaitUntil = WaitUntilState.NetworkIdle, Timeout = 90000 });
        await page.Run("() => document.fonts.ready.then(() => undefined)");
        var measured = (await page.Run("""
            ({ CHARS, WEIGHTS }) => {
              const text = document.createElementNS('http://www.w3.org/2000/svg', 'text');
              text.style.whiteSpace = 'pre';
              text.style.fontSize = '2048px';
              document.querySelector('ui-chart svg').appendChild(text);
              const width = s => { text.textContent = s; return text.getComputedTextLength(); };
              const out = {};
              for (const weight of WEIGHTS) {
                text.style.fontWeight = weight;
                // A lone space has no length of its own: it is measured between two letters, and so is a pair with one.
                const x = width('x');
                const single = CHARS.map(c => Math.round(c === ' ' ? width('x x') - 2 * x : width(c)));
                const pairs = [];
                CHARS.forEach((a, i) => CHARS.forEach((b, j) => {
                  const kern = a === ' ' && b === ' ' ? 0
                    : a === ' ' ? width('x' + a + b) - width('x ') - single[j]
                    : b === ' ' ? width(a + b + 'x') - single[i] - width(' x')
                    : width(a + b) - single[i] - single[j];
                  if (Math.abs(kern) > 0.4) pairs.push((i << 17) | (j << 10) | (Math.round(kern) + 512));
                }));
                out[weight] = { single, pairs };
              }
              text.remove();
              return out;
            }
            """, new { CHARS = chars, WEIGHTS = Weights }))!;
        await browser.CloseAsync();

        static string Rows(JsonArray values, int per)
        {
            var lines = new List<string>();
            for (var i = 0; i < values.Count; i += per)
            {
                lines.Add("        " + string.Join(", ", values.Skip(i).Take(per).Select(v => Js.Num(Js.Number(v)))) + ",");
            }

            return string.Join('\n', lines);
        }

        var glyphs = string.Concat(chars.Select(c => c is "\"" or "\\" ? "\\" + c : c));
        var tables = string.Join('\n', Weights.Select(weight =>
        {
            var w = weight.ToString(CultureInfo.InvariantCulture);
            return $"""

                    // Advance width of each glyph at weight {w}, in font units (2048 to the em).
                    private static readonly short[] Advance{w} =
                    [
                {Rows((JsonArray)measured[w]!["single"]!, 20)}
                    ];

                    // Kerning pairs at weight {w}: (left << 17) | (right << 10) | (units + 512).
                    private static readonly int[] Kerning{w} =
                    [
                {Rows((JsonArray)measured[w]!["pairs"]!, 12)}
                    ];
                """;
        }));
        var source = new StringBuilder()
            .Append("// <auto-generated>scripts/flux/Flux (flux inter-metrics) — do not edit by hand.</auto-generated>\n")
            .Append("namespace Rask;\n\n")
            .Append("internal static partial class UiChartInter\n{\n")
            .Append("    // The glyphs measured, in the order of every table below.\n")
            .Append($"    private const string Glyphs = \"{glyphs}\";\n")
            .Append(tables.Replace("\r\n", "\n", StringComparison.Ordinal))
            .Append("\n}\n")
            .ToString();
        await File.WriteAllTextAsync(Repo.Path("src", "Rask.Ui", "UiChartInter.Metrics.cs"), source);
        Console.WriteLine($"inter metrics: {string.Join(", ", Weights.Select(w => $"{w}: {((JsonArray)measured[w.ToString(CultureInfo.InvariantCulture)]!["pairs"]!).Count} pairs"))}");
        return 0;
    }
}
