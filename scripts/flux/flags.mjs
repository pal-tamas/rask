#!/usr/bin/env node
// Vendors the flag artwork Ui.Flag draws: country-flag-icons' 3:2 set.
//
// country-flag-icons (https://gitlab.com/catamphetamine/country-flag-icons) is MIT-licensed,
// Copyright (c) 2020 @catamphetamine. It is the set Flux UI's `flux:flag` serves: 250 of the files on
// fluxui.dev are byte-for-byte the project's sources and 4 its minified ones. The npm tarball — the same
// drawings, minified by the project itself — is npm's latest release, checked against the registry's integrity,
// read in memory, and never unpacked to disk. Out of its `3x2` folder come:
//
//   src/Rask.Ui/Flags/<CC>.svg         one file per region code, served as a static file (never embedded)
//   src/Rask.Ui/Flags/LICENSE.txt      the project's licence, with the release
//   src/Rask.Ui/UiFlagRegistry.g.cs    which codes there are, and the release the URLs carry
//
// NOT here: UN and CQ (Sark). Unicode's RGI list has them and Flux serves them, but from artwork that is
// not this project's and whose licence could not be established. Ui.Flag draws its empty frame for them.
//
// Usage:  node scripts/flux/flags.mjs            # regenerate from the latest release
//         node scripts/flux/flags.mjs --check    # exit 1 when the committed files are not that release's
//
// scripts/upstream/follow.sh runs it every day.

import { mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { gunzipSync } from 'node:zlib';
import { fail as failAs, latest, tarball, untar } from '../upstream/npm.mjs';
import { root } from './lib.mjs';

const LABEL = 'flux flags';
const release = await latest('country-flag-icons', LABEL);
const VERSION = release.version;

// Private-use codes the project draws and Flux's registry does not answer for.
const NOT_FLUX = ['XA', 'XC', 'XO'];
// Unicode gives these three the flag of the country they belong to. One file each, not two.
const ALIASES = { CP: 'FR', DG: 'IO', EA: 'ES' };

const files = untar(gunzipSync(await tarball(release, LABEL)));
const flags = new Map();
for (const [path, svg] of files) {
  const code = /^package\/3x2\/([A-Z]{2})\.svg$/.exec(path)?.[1];
  if (!code || NOT_FLUX.includes(code)) continue;
  // Served to an <img>, where nothing in an SVG runs — and still held to plain artwork.
  if (!/^<svg [^>]*viewBox="[\d. ]+"[^>]*>.*<\/svg>\s*$/s.test(svg) || /<script|<foreignObject|\son\w+=|href="(?!#)/i.test(svg)) {
    fail(`${path}: not plain artwork`);
  }

  flags.set(code, svg);
}

if (flags.size < 250) fail(`only ${flags.size} flags in the tarball`);
for (const [alias, target] of Object.entries(ALIASES)) {
  if (flags.has(alias) || !flags.has(target)) fail(`alias ${alias} -> ${target} no longer holds`);
}

const licence = files.get('package/LICENSE') ?? fail('no LICENSE in the tarball');
const folder = join(root, 'src', 'Rask.Ui', 'Flags');
const outputs = new Map([
  [join(folder, 'LICENSE.txt'), `country-flag-icons ${VERSION} — https://gitlab.com/catamphetamine/country-flag-icons\n`
    + `The .svg files in this folder are that project's 3x2 flags, unmodified. Generated by scripts/flux/flags.mjs.\n\n${licence}`],
  [join(root, 'src', 'Rask.Ui', 'UiFlagRegistry.g.cs'), registrySource()],
  ...[...flags].map(([code, svg]) => [join(folder, `${code}.svg`), svg]),
]);

const check = process.argv.includes('--check');
const present = (await readdir(folder).catch(() => [])).map(name => join(folder, name));
const strays = present.filter(path => !outputs.has(path));
let stale = strays.length;
if (!check) {
  await mkdir(folder, { recursive: true });
  for (const path of strays) await rm(path);
}

for (const [path, text] of outputs) {
  if (check) stale += (await readFile(path, 'utf8').catch(() => '')) === text ? 0 : 1;
  else await writeFile(path, text);
}

if (check && stale) fail(`${stale} generated file(s) are stale — run: node scripts/flux/flags.mjs`);
console.log(`flux flags: country-flag-icons ${VERSION} — ${flags.size} flags, `
  + `${[...flags.values()].reduce((sum, svg) => sum + Buffer.byteLength(svg), 0)} bytes of SVG.`);

function registrySource() {
  const codes = [...flags.keys()].sort().join('');
  const aliases = Object.entries(ALIASES).map(([alias, target]) => `            "${alias}" => "${target}",`).join('\n');
  return `// <auto-generated>
// Generated by scripts/flux/flags.mjs from country-flag-icons ${VERSION} (MIT, Copyright (c) 2020 @catamphetamine),
// ${release.dist.tarball}, ${release.dist.integrity}.
// Do not edit: change the script and run it.
// </auto-generated>

#nullable enable

namespace Rask;

/// <summary>Which region codes <see cref="UiFlag" /> has a drawing for: the files in <c>Flags/</c>.</summary>
internal static class UiFlagRegistry
{
    /// <summary>The release the drawings come from. It rides on every flag URL, so a new set is fetched anew.</summary>
    internal const string Version = "${VERSION}";

    // Every code, two letters each, in order.
    private const string Codes =
        "${codes}";

    /// <summary>The file that draws <paramref name="country" />, or <see langword="null" /> when there is none.</summary>
    internal static string? File(string country)
    {
        if (country.Length != 2 || !char.IsAsciiLetter(country[0]) || !char.IsAsciiLetter(country[1]))
        {
            return null;
        }

        var code = country.ToUpperInvariant() switch
        {
${aliases}
            var upper => upper,
        };

        for (var at = 0; at < Codes.Length; at += 2)
        {
            if (Codes[at] == code[0] && Codes[at + 1] == code[1])
            {
                return code;
            }
        }

        return null;
    }
}
`;
}

function fail(message) {
  failAs(LABEL, message);
}
